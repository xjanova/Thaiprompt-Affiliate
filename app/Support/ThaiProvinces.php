     * @return string|null ชื่อทางการ · null = ไม่พบที่เกิดในข้อความ
     */
    public static function resolveBirthplace(string $text): ?string
    {
        $text = trim($text);
        if ($text === '') {
            return null;
        }

        // คำถามจริงสั้นกว่านี้มาก — ตัดไว้กัน JIT stack หมดกับข้อความยาวผิดปกติ (คืน false = เงียบ)
        $haystack = preg_replace('/\s+/u', ' ', mb_substr($text, 0, self::BIRTH_TEXT_MAX)) ?? $text;

        $best = null;
        $bestRank = null;

        foreach (self::candidates() as $needle => $official) {
            if (mb_strpos($haystack, $needle) === false) {
                continue;
            }

            // ⚠️ ห้ามใช้ {0,N} กับกลุ่มคั่น — PCRE คอมไพล์ด้วยการก็อปกลุ่มทั้งก้อน N รอบ
            //    ⇒ "regular expression is too large" (เจอในเทสต์ก่อนพุช) · ใช้ *? แล้วคุมความยาวจากช่วงที่จับได้แทน
            $re = '/'.self::BIRTH_NOT_THIRD_PARTY.self::BIRTH_CUE
                .'((?:'.self::BIRTH_FILLER.')*?)'.preg_quote($needle, '/').'/u';
            if (! preg_match_all($re, $haystack, $m, PREG_OFFSET_CAPTURE)) {
                continue;
            }

            foreach ($m[1] as $k => [$between, $offset]) {
                if (mb_strlen($between) > self::BIRTH_SPAN_MAX) {
                    continue;
                }
                // ชื่อกำกวม ("เลย" "ตาก") ต้องมีคำบอกสถานที่ในช่วง — "เกิดเลย" = "เกิดเลย" ไม่ใช่ จ.เลย
                if (in_array($needle, self::NEEDS_CUE, true)
                    && ! preg_match('/(?:ที่|ใน|จังหวัด|จ\.|อำเภอ|อ\.|(?:อำเภอ|อ\.)\s*เมือง)\s*$/u', $between)) {
                    continue;
                }
                // "รพ.กรุงเทพภูเก็ต" = ชื่อเครือโรงพยาบาล ไม่ใช่เกิดกรุงเทพ — มีชื่อจังหวัดอื่นต่อท้ายติดกัน ⇒ ข้ามไปใช้ตัวหลัง
                //   (ตัวหลังเดินผ่านชื่อเครือได้ด้วยช่องคั่น BIRTH_FILLER "รพ.กรุงเทพ" ที่ต้องมีอักษรไทยตามติด)
                if ($official === 'กรุงเทพมหานคร'
                    && preg_match('/(?:โรงพยาบาล|รพ\.?)\s*$/u', $between)
                    && self::startsWithOtherProvince(ltrim(substr($haystack, $m[0][$k][1] + strlen($m[0][$k][0])), ' '), $official)) {
                    continue;
                }
                // บุคคลที่สามที่ lookbehind มองไม่เห็น (มีคำขยาย/สรรพนามคั่น) — "แฟนผมเกิดที่ภูเก็ต"
                //   ออฟเซ็ตเป็นไบต์ ⇒ ตัดด้วย substr แล้วค่อยนับตัวอักษรย้อน 40 ตัว
                if (preg_match(self::BIRTH_THIRD_PARTY_TAIL, mb_substr(substr($haystack, 0, $m[0][$k][1]), -40))) {
                    continue;
                }
                // ลำดับ: [ถ้อยคำ "เป็นคน…" (บ้านเดิม) ด้อยกว่าบอกที่เกิดตรงๆ, ตำแหน่งไบต์ที่ชื่อจังหวัดถูกพูดถึง]
                //   🐛 (จับผี) เดิมใช้ตำแหน่งหลังคำบ่งชี้ — จังหวัดที่ตามคำว่าเกิดตัวเดียวกันเสมอกันหมด
                //      ⇒ "เกิดที่อำเภอเมืองลำปาง … ที่ภูเก็ต" ได้ชื่อที่ถูกไล่ก่อน (ยาวกว่า) ไม่ใช่ที่พูดก่อน
                $rank = [str_contains($between, 'เป็นคน') ? 1 : 0, $offset + strlen($between)];
                if ($bestRank === null || $rank < $bestRank) {
                    $best = $official;
                    $bestRank = $rank;
                }
            }
        }

        return $best;
    }

    /** ข้อความขึ้นต้นด้วยชื่อจังหวัดอื่น (ไม่ใช่ $official) ติดกันเลยไหม — ใช้แยกชื่อเครือโรงพยาบาล "กรุงเทพภูเก็ต" */
    private static function startsWithOtherProvince(string $rest, string $official): bool
    {
        foreach (self::candidates() as $name => $other) {
            if ($other !== $official && str_starts_with($rest, $name)) {
                return true;
            }
        }

        return false;
    }

    /** ความยาวข้อความสูงสุดที่อ่าน (ตัวอักษร) */
    private const BIRTH_TEXT_MAX = 2000;

    /**
     * ระยะสูงสุดระหว่างคำบ่งชี้กับชื่อจังหวัด (ตัวอักษร นับสระ/วรรณยุกต์ด้วย)
     * "เกิดวันพฤหัสบดีที่ 15 เดือนพฤษภาคม พ.ศ. 2533 เวลาประมาณ 08:30 น. ตอนเช้า ที่อำเภอเมือง จังหวัด" ≈ 90
     * ช่วงคั่นรับแต่รายละเอียดการเกิดอยู่แล้ว เพดานหลวมจึงปลอดภัย
     */
    private const BIRTH_SPAN_MAX = 160;

    /**
     * ไม่ใช่การเกิดของเจ้าชะตา — คำเรียกคนอื่น/สัตว์เลี้ยง หรือ "จะ" (อนาคต) ติดหน้าคำบ่งชี้
     * (lookbehind แต่ละตัวยาวคงที่ — PCRE ยอมให้ความยาวต่างกันได้เมื่อแยกเป็นทางเลือกระดับบนสุด)
     */
    private const BIRTH_NOT_THIRD_PARTY = '(?<!แฟน|สามี|ภรรยา|เมีย|ผัว|ลูก|พ่อ|แม่|พี่|น้อง|เพื่อน|หลาน|เขา|หมา|แมว|จะ|แฟน |ลูก |แม่ |พ่อ |จะ '
        // "เรื่องที่เกิดในกรุงเทพ" = เหตุการณ์ที่เกิดขึ้น ไม่ใช่การเกิดของคน ("สถานที่เกิด" ยังผ่าน)
        .'|เรื่อง|เรื่องที่|สิ่งที่|เหตุการณ์ที่|ปัญหาที่|มัน)';

    /**
     * ท้ายข้อความก่อนคำบ่งชี้ ที่บอกว่าเป็นการเกิดของ "คนอื่น" — คำเรียกญาติ/แฟน/สัตว์เลี้ยง + คำขยาย + สรรพนามเจ้าของ
     *
     * lookbehind ข้างบนเห็นแค่คำที่ติดคำบ่งชี้ ⇒ "แฟนผมเกิดที่ภูเก็ต" · "แม่ของหนูเกิดที่อุดร" · "แฟนเก่าเกิดที่…" หลุดไปเป็นที่เกิดของเจ้าชะตา
     * สรรพนามต้องติดคำเรียกญาติ (หรือผ่าน "ของ") — "แม่ หนูเกิดที่ขอนแก่น" (เรียกแม่หมอ แล้วพูดถึงตัวเอง) ต้องไม่โดนตัด
     * ⚠️ ไม่ตัด: ชื่อเล่น "น้องมิวเกิดที่…" (ลูกค้าเรียกตัวเอง) · คำเรียกเปล่าๆ แล้วเว้นวรรค "สวัสดีครับพี่ เกิด…" (เรียกคนฟัง)
     *    · "หนูเป็นลูกคนเล็ก เกิดที่…" (บอกว่าตัวเองเป็นใคร — "เป็น" + คำขยาย ไม่มีสรรพนามเจ้าของ)
     * 3 ทาง: [ญาติ+คำขยาย (ไม่ใช่ "เป็น…")] · [ญาติ+คำขยาย?+(ของ)สรรพนาม+คำตาม?] · [ญาติติดคำบ่งชี้เลย]
     */
    private const BIRTH_THIRD_PARTY_TAIL = '/(?:'
        .'(?<!เป็น)(?<!เป็น )'.self::KIN.'(?:'.self::KIN_MOD.'){1,2}\s*'
        .'|'.self::KIN.'(?:'.self::KIN_MOD.'){0,2}(?:\s*ของ\s*)?'.self::OWNER_PRONOUN.'(?:คนนี้|คนนั้น|เค้า|เขา|เอง)?\s*'
        .'|'.self::KIN
        .')$/u';

    private const KIN = '(?:แฟน|สามี|ภรรยา|ภริยา|เมีย|ผัว|ลูก|พ่อ|แม่|พี่|น้อง|เพื่อน|หลาน|ปู่|ย่า|ยาย|ญาติ|หมา|แมว|เขา|เธอ)';

    private const KIN_MOD = 'เก่า|ใหม่|สนิท|ชาย|สาว|ตา|ยาย|คนนี้|คนนั้น|คนแรก|คนเล็ก|คนโต';

    private const OWNER_PRONOUN = '(?:ผม|หนู|ฉัน|ชั้น|ดิฉัน|เรา|กู|ข้า|เค้า|พี่|น้อง)';

    /** คำบ่งชี้ว่ากำลังพูดถึง "การเกิด" — ตัด "เกิดอะไร/เกิดเรื่อง/เกิดขึ้น…" (คำถามดูดวงที่พบบ่อยที่สุด) */
    private const BIRTH_CUE = '(?:บ้านเกิด(?:ของ)?(?:หนู|ผม|ฉัน|ดิฉัน|เรา)?(?:อยู่|คือ)?|เกิด(?!อะไร|เรื่อง|ปัญหา|ขึ้น|ผล|เหตุ|ความ)|คลอด|ลืมตา(?:ดูโลก)?)';

    /**
     * สิ่งที่คั่นระหว่างคำบ่งชี้กับชื่อจังหวัดได้ — รายละเอียดการเกิดล้วน (ไม่มีกริยาอื่นแทรก)
     *
     * ชื่อตำบล/อำเภอ/เขต/โรงพยาบาล รับได้ 1 คำ เฉพาะเมื่อมีคำนำหน้า และต้องจบด้วยช่องว่าง ("อ.แม่สาย จ.เชียงราย" · "รพ.มหาราช เชียงใหม่")
     *   🐛 (จับผี) ไม่บังคับช่องว่าง = กลืนกริยาที่พิมพ์ติดกันไปด้วย "เกิดที่อ.เมืองอยู่ภูเก็ต" → ภูเก็ต
     *   ความยาวคุมด้วย {0,20} บน character class (ไม่ใช่กลุ่ม — กลุ่มซ้ำ N รอบทำ regex ใหญ่เกิน)
     * เดือนภาษาอังกฤษต้องจบคำ — "maybe" "married" "decided" ห้ามนับเป็นเดือน
     * ⚠️ ห้ามเติม "อยู่" — "เกิด 5 พ.ค. 33 อยู่ภูเก็ต" = อาศัยอยู่ · ห้าม "เติบโต" เดี่ยวๆ — "โตที่ภูเก็ต" ไม่ใช่ที่เกิด
     */
    private const BIRTH_FILLER = '[\s0-9๐-๙\/\.:\-,ๆ]|เวลา|ตอน|ประมาณ|ราว|เมื่อ|ณ|ที่|ใน|แถว|จังหวัด|จ\.|อำเภอ|อ\.|เมือง'
        .'|(?:ตำบล|ต\.|อำเภอ|อ\.|เขต|แขวง|โรงพยาบาล|รพ\.?)\s*[ก-ฮเ-ไ][ก-๙]{0,20}(?=\s)'
        .'|(?:โรงพยาบาล|รพ\.?)\s*กรุงเทพ(?=[ก-ฮเ-ไ])'
        .'|(?:และ|แล้ว)(?:เติบ)?โต|เป็นคน|คือ'
        .'|(?i:january|february|march|april|may|june|july|august|september|october|november|december|jan|feb|mar|apr|jun|jul|aug|sept|sep|oct|nov|dec)\.?(?![a-zA-Z])'
