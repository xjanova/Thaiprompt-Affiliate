        $statedHour = $birthHour ?? $this->extractStatedBirthHour($text);
        $this->lastBirthHour = $statedHour;

        $multi = count($dates) > 1;
        $people = '';
        $ownerBasis = 'none';

        foreach ($dates as $i => $d) {
            // ป้ายกำกับคน — ถ้ามีหลายคนให้ระบุลำดับ เพื่อให้ AI map กับบริบท (เจ้าชะตา vs คู่/อีกฝ่าย)
            $label = $multi
                ? '👤 คนที่ '.($i + 1)." (เกิด {$d['raw']})"
                : "👤 เจ้าของวันเกิด (เกิด {$d['raw']})";

            // 🕛 (2026-09-03) ส่ง "เวลาเกิดที่ลูกค้าบอก" เข้าไปด้วย — เดิมส่ง null
            //
            //   ⚠️ บั๊กเดิม (ทั้งเลน Celtic 99฿): เราคำนวณ $statedHour ไว้แล้วบรรทัดบน แต่ส่ง null
            //     ⇒ formatPersonBlock() เข้า else "วันที่ล้วน = ไม่ทราบเวลา" แล้ว **ล้าง
            //       lastBirthHour = null ทิ้ง** (ตัว ymd เป็น 'Y-m-d' ล้วน regex H:i ไม่แมตช์)
            //     ⇒ ทุกอย่างที่เดินจากเวลาเกิดพังเงียบ: ลัคนาถอยไปใช้เวลามาตรฐาน 12:00,
            //       วันทางโหร (ย่ำรุ่ง 06:00) ไม่ shift, พุธกลางคืน→ราหู ไม่ทำงาน,
            //       ทักษา/มหาทักษา/วันมงคล เดินจากดาวเจ้าชนะผิดดวง
            //     เคสจริง: เกิด 27/6/1978 02:30 → ผังบอก "วันอังคาร · ดาวอังคาร · ธาตุไฟ ·
            //       ลัคนากันย์ (⏱️ เจ้าชะตายังไม่ได้บอกเวลาเกิด)" ทั้งที่ของจริงคือ
            //       "วันจันทร์กลางคืน · ดาวจันทร์ · ธาตุน้ำ · ลัคนาเมษ" ⇒ พื้นดวงขัดกับที่ลูกค้าพิมพ์มาเอง
            //
            //   เวลาที่ parse ได้เป็นของ "เจ้าชะตา" (คนแรก) เท่านั้น — คนที่ 2-3 (คู่/อีกฝ่าย)
            //   ลูกค้าแทบไม่เคยบอกเวลาเกิดให้ ⇒ ส่ง null ให้ไปใช้เวลามาตรฐาน ไม่ยืมเวลาคนแรกมาใช้
            // 🗺️ จังหวัดเกิดก็เป็นของ "เจ้าชะตา" คนแรกเท่านั้น — เหตุผลเดียวกับเวลาเกิด
            //    ลูกค้าไม่เคยบอกจังหวัดเกิดของคู่/คู่ปรับ ⇒ ยืมมาใช้ = ผูกดวงคนอื่นด้วยพิกัดผิด
            $people .= $label."\n".$this->formatPersonBlock(
                $d['ymd'],
                $i === 0 ? $statedHour : null,
                $i === 0,
                $i === 0 ? ($birthProvince ?? \App\Support\ThaiProvinces::resolve($text)) : null
            )."\n";

            // 🕛 (2026-09-09) ฐานที่ใช้นับภพ = ของ "เจ้าชะตา" (คนแรก) เท่านั้น
            //    ⚠️ ห้ามอ่าน $this->lastLagnaBasis หลังลูป — คนที่ 2-3 (คู่/คู่ปรับ) ไม่เคยมีเวลาเกิด
            //      ฐานของเขาจะทับของเจ้าชะตา ⇒ คำสั่งท้ายบล็อกจะสั่งผิดคน
            if ($i === 0) {
                $ownerBasis = $this->lastLagnaBasis;
            }
        }

