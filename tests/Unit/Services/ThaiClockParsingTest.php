    public function test_อ่านนาฬิกาไทยเป็นเวลาสากลได้(string $input, ?float $expected): void
    {
        $this->assertSame(
            $expected,
            $this->svc->parseThaiClock($input),
            "อ่าน \"{$input}\" ไม่ตรงกับที่คาดไว้"
        );
    }

