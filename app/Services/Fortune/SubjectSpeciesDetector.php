    /**
     * วิเคราะห์ข้อความ → ชนิดของ "ตัวละครในคำถาม"
     *
     * @param  string  $text  ข้อความลูกค้า (รวมคำถามเก่าได้ ยิ่งมีบริบทยิ่งแม่น)
     * @return array{kind:string, species:?string, breed:?string, signals:array<string>}
     */
    public static function analyze(string $text): array
    {
        $none = ['kind' => self::KIND_HUMAN, 'species' => null, 'breed' => null, 'signals' => []];

        $raw = trim($text);
        if ($raw === '') {
            return $none;
        }

        $h = mb_strtolower($raw);
        $signals = [];

        // 1️⃣ ชนิดสัตว์ที่ระบุตรง ๆ = ชัดที่สุด
        $species = null;
        foreach (self::SPECIES_PATTERNS as $name => $pattern) {
            if (preg_match($pattern, $h, $m)) {
                $species = $name;
                $signals[] = trim((string) ($m[0] ?? $name));
                break;
            }
        }

        // 2️⃣ บริบทสัตว์ (ปลอกคอ/เห่า/ติดสัด/สัตวแพทย์ ...)
        $petContextHits = [];
        foreach (self::PET_CONTEXT as $kw) {
            if (mb_strpos($h, $kw) !== false) {
                $petContextHits[] = $kw;
            }
        }

        if ($species !== null) {
            return [
                'kind' => self::KIND_PET,
                'species' => $species,
                'breed' => self::extractBreed($h),
                'signals' => array_slice(array_merge($signals, $petContextHits), 0, 6),
            ];
        }

        // 3️⃣ ไม่ระบุชนิด — ดูว่าประธานเป็น "น้อง" ลอย ๆ หรือเปล่า
        $hasHumanMarker = false;
        foreach (self::HUMAN_MARKERS as $kw) {
            if (mb_strpos($h, $kw) !== false) {
                $hasHumanMarker = true;
                break;
            }
        }

        if ($hasHumanMarker || mb_strpos($h, 'น้อง') === false) {
            return $none;
        }

        // "น้อง" ลอย ๆ + บริบทสัตว์ ⇒ เป็นสัตว์เกือบแน่ (แต่ไม่รู้ชนิด)
        if ($petContextHits !== []) {
            return [
                'kind' => self::KIND_PET,
                'species' => null,
                'breed' => self::extractBreed($h),
                'signals' => array_slice($petContextHits, 0, 6),
            ];
        }

        // "น้อง" ลอย ๆ + กำลังถามถึงชะตาของ "น้อง" คนนั้น ⇒ กำกวม ต้องถามก่อน
        foreach (self::SUBJECT_CONTEXT as $kw) {
            if (mb_strpos($h, $kw) !== false) {
                return [
                    'kind' => self::KIND_UNKNOWN,
                    'species' => null,
                    'breed' => null,
                    'signals' => ['น้อง', $kw],
                ];
            }
        }

        return $none;
    }

