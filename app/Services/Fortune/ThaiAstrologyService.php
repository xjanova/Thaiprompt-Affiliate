    /**
     * ✍️ ชื่อมงคล (อักษรทักษา) — อักษรมงคลควรมีในชื่อ + อักษรกาลกิณีห้ามใช้
     *   เดช(2)/ศรี(3)/มนตรี(6) = อักษรดี · กาลกิณี(7) = อักษรห้าม
     */
    protected function formatNamingLine(int $dayOfWeek): string
    {
        $thaksa = $this->getThaksa($dayOfWeek, $this->lastBirthHour);
        $letters = (array) config('thai_astrology_knowledge.naming_letters', []);
        if (empty($thaksa) || empty($letters)) {
            return '';
        }

        $dechP = $thaksa[2]['planet'] ?? '';
        $sriP = $thaksa[3]['planet'] ?? '';
        $montriP = $thaksa[6]['planet'] ?? '';
        $kalaP = $thaksa[7]['planet'] ?? '';

        $good = [];
        if (isset($letters[$dechP])) {
            $good[] = "เดช: {$letters[$dechP]}";
        }
        if (isset($letters[$sriP])) {
            $good[] = "ศรี: {$letters[$sriP]}";
        }
        if (isset($letters[$montriP])) {
            $good[] = "มนตรี: {$letters[$montriP]}";
        }

        $out = '';
        if (! empty($good)) {
            $out .= '✍️ ชื่อมงคล (อักษรควรมีในชื่อ) — '.implode(' | ', $good)."\n";
        }
        if (isset($letters[$kalaP])) {
            $out .= "🚫 อักษรกาลกิณี (ห้ามใช้ในชื่อ): {$letters[$kalaP]}\n";
        }

        return $out;
    }

    /**
     * 🕛 หน้าต่างข้อความนี้ "พูดถึงเวลา" จริงไหม — ใช้กันเลขเปล่าถูกอ่านเป็นนาฬิกา
     *
     * ผ่านเมื่อมีอย่างใดอย่างหนึ่ง:
     *   • รูปนาฬิกาที่มี `:` เช่น 02:30 (คนไม่เขียนราคา/หนี้ด้วยโคลอน)
     *   • คำบอกเวลาไทย/อังกฤษ: น. · นาฬิกา · โมง · ทุ่ม · ตี · เวลา · ช่วงเวลาของวัน · am/pm
     *
     * ❌ ไม่ผ่าน: "หนี้ 2.30 แสน" · "เงินเดือน 12.50" · "ผ่อนบ้าน 8.30 ปี"
     */
    protected function windowHasTimeMarker(string $window): bool
    {
        $w = $this->normalizeThaiDigits($window);

        // รูป HH:MM (โคลอน) — สัญญาณว่าเป็นนาฬิกาที่ชัดที่สุด
        if (preg_match('/(?<!\d)\d{1,2}:\d{2}(?!\d)/u', $w)) {
            return true;
        }

        // คำบอกเวลา — "น." ต้องตามหลังตัวเลข (กัน "น." ที่เป็นตัวอักษรในคำอื่น)
        if (preg_match('/\d\s*น\.?(?![ก-๙])/u', $w)) {
            return true;
        }

        foreach (['นาฬิกา', 'โมง', 'ทุ่ม', 'ตี', 'เวลา', 'เช้าตรู่', 'เช้า', 'สาย', 'เที่ยง',
            'บ่าย', 'เย็น', 'ค่ำ', 'ดึก', 'กลางคืน', 'กลางวัน', 'am', 'pm', 'AM', 'PM'] as $marker) {
            if (mb_strpos($w, $marker) !== false) {
                return true;
            }
        }

        return false;
    }

