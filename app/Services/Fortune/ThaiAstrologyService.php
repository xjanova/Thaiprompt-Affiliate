    /** 🕛 ชั่วโมง (float) → "HH:MM" สำหรับโชว์ในผัง */
    public static function hourLabel(?float $hour): string
    {
        if ($hour === null) {
            return '-';
        }
        $h = (int) floor($hour);
        $m = (int) round(($hour - $h) * 60);
        if ($m >= 60) {
            $h++;
            $m = 0;
        }

        return sprintf('%02d:%02d', $h % 24, $m);
    }

