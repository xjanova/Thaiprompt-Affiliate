        $this->command->info('🌱 กำลัง seed ข้อความชวนรับดวงรายวันฟรี ชุดที่ 2 (50 ข้อความ)...');

        $groups = $this->groups();
        $categories = array_column($groups, 'category');

        // ✅ idempotent — เคย seed ชุดนี้แล้วข้ามเลย
        //    ⚠️ ใช้ withTrashed() ด้วย: ถ้าแอดมินลบข้อความที่ไม่ชอบทิ้ง
        //    ต้องไม่ปลุกกลับมาทุกครั้งที่ deploy (firstOrCreate ต่อข้อความทำแบบนี้ไม่ได้)
        if (FortuneInviteMessage::withTrashed()->whereIn('category', $categories)->exists()) {
            $this->command->info('   มีข้อความชุดที่ 2 อยู่แล้ว ข้าม...');

            return;
        }

        // ⏰ ยังไม่ได้ migrate คอลัมน์ช่วงเวลา → สร้างแบบไม่ผูกเวลาไปก่อน
        //    (ข้อความยังใช้ได้ทุกข้อ แค่โทนเวลาอาจเพี้ยนจนกว่าแอดมินจะตั้งเอง)
        $hasWindow = FortuneInviteMessage::supportsTimeWindow();

        if (! $hasWindow) {
            $this->command->warn('   ⚠️ ยังไม่มีคอลัมน์ hour_from/hour_to → ข้ามการตั้งช่วงเวลา');
        }

        $sort = (int) (FortuneInviteMessage::max('sort_order') ?? 0);
        $created = 0;

        foreach ($groups as $group) {
            foreach ($group['messages'] as $text) {
                $row = [
                    'message' => $text,
                    'category' => $group['category'],
                    'mode' => FortuneInviteMessage::MODE_DAILY,
                    'is_active' => true,
                    'sort_order' => ++$sort,
                ];

                if ($hasWindow) {
                    $row['hour_from'] = $group['hour_from'];
                    $row['hour_to'] = $group['hour_to'];
                }

                FortuneInviteMessage::create($row);
                $created++;
            }
        }

        $total = FortuneInviteMessage::where('mode', FortuneInviteMessage::MODE_DAILY)->count();

        $this->command->info("✅ Seed ชุดที่ 2 สำเร็จ — เพิ่ม {$created} ข้อความ (ชุด daily รวม {$total} ข้อความ)");
    }

