        $directive = "👉 วิธีใช้ดวงดาวนี้ (สำคัญ):\n"
            ."• ผสาน ราศี/ดาวเจ้าชนะ/ธาตุ/พื้นนิสัย เข้ากับไพ่ที่เปิดไว้ — อย่าทำนายจากไพ่อย่างเดียว\n"
