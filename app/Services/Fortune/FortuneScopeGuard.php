    /**
     * ตรวจว่าข้อความคือการ "ขุดข้อมูล" หรือไม่
     *
     * @param  string  $text  ข้อความดิบของลูกค้า (ห้ามส่งพรอมต์ที่ระบบสร้าง)
     * @return string|null category ('chant' / 'recipe' / ...) | null = ไม่ใช่
     */
    public static function detectExtraction(string $text): ?string
    {
        $text = trim($text);

        // 🛟 ด่านแรก: ต้องเป็น "คำสั่งสั้น ๆ" เท่านั้น
        //    ยาวกว่านี้ = เล่าเรื่อง/บรรยายปัญหา → ห้ามแตะ (ปล่อยหลุดดีกว่ากลืน)
        if ($text === '' || mb_strlen($text) > self::MAX_COMMAND_LEN) {
            return null;
        }

        // 🚨 กันซ้ำรอย PROD-DOWN 2026-06-27 — ผู้เรียกหลายจุดประกอบพรอมต์เองแล้วยัด
        //   ข้อความลูกค้าไว้ข้างใน พรอมต์พวกนี้มีคำอย่าง "สรุปให้"/"เขียนคำทำนาย" อยู่เอง
        if (self::looksLikeSystemPrompt($text)) {
            return null;
        }

        $lower = mb_strtolower($text);

        // 🛟 ด่านสอง: มีเค้าเรื่องดวง/ชีวิต/เงิน/ระบบ แม้คำเดียว → ปล่อยให้ AI ตอบ
        //    ครอบทั้ง chant ด้วย — เลนนั้นให้ promptDirective() + stripChantText() จัดการแทน
        //    ([[rule_gate_must_not_swallow_customer_text]])
        foreach (self::FORTUNE_SIGNALS as $signal) {
            if (mb_strpos($lower, $signal) !== false) {
                return null;
            }
        }

        // 🪬 ขอบทสวด/คาถา "ล้วน ๆ" — สั้น + ไม่มีเค้าเรื่องดวงเลย
        foreach (self::chantRequestPatterns() as $pattern) {
            if (preg_match($pattern, $lower)) {
                return 'chant';
            }
        }

        foreach (self::EXTRACTION_PATTERNS as $category => $patterns) {
            foreach ($patterns as $pattern) {
                if (preg_match($pattern, $lower)) {
                    return $category;
                }
            }
        }

        return null;
    }

    protected static function looksLikeSystemPrompt(string $text): bool
    {
        foreach (self::SYSTEM_PROMPT_MARKERS as $marker) {
            if (mb_strpos($text, $marker) !== false) {
                return true;
            }
        }

        // พรอมต์ที่ระบบสร้างมักเป็นคำสั่งหลายบรรทัด — ลูกค้าพิมพ์ขอบทสวดไม่เขียน 4 บรรทัด
        return substr_count($text, "\n") >= 4;
