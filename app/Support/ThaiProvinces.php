    /**
     * ชื่อจังหวัดที่เป็นคำไทยธรรมดาด้วย — ห้ามจับลอย ๆ ต้องมีคำนำหน้าบอกว่าเป็นสถานที่
     *
     * "ไปเลยค่ะ" · "ตากแดด" · "แพร่หลาย" · "น่านน้ำ" — กับดักประเภทเดียวกับที่เคยพังมาแล้ว
     *
     * @var array<int, string>
     */
    public const NEEDS_CUE = ['เลย', 'ตาก', 'แพร่', 'น่าน', 'ตรัง', 'นนท์'];

    /** คำนำหน้าที่ยืนยันว่าคำถัดไปคือสถานที่ */
    private const CUE = '(?:จังหวัด|จ\.|ที่|อยู่|เกิดที่|เกิด|บ้าน|อำเภอ|อ\.)\s*';

    /**
     * หาชื่อจังหวัดในข้อความ — คืนชื่อมาตรฐาน หรือ null ถ้าไม่พบ
     *
     * @param  string  $text  ข้อความจากลูกค้า
     */
    public static function resolve(string $text): ?string
    {
        $text = trim($text);
        if ($text === '') {
            return null;
        }

        // ทำความสะอาดเบา ๆ — ยุบวรรคซ้ำ ไม่แตะตัวอักษรไทย (ห้าม trim ทีละไบต์)
        $haystack = preg_replace('/\s+/u', ' ', $text) ?? $text;

        foreach (self::candidates() as $needle => $official) {
            if (mb_strpos($haystack, $needle) === false) {
                continue;
            }

            if (in_array($needle, self::NEEDS_CUE, true)
                && ! self::cueSatisfied($haystack, $needle)) {
                continue;
            }

            return $official;
        }

        return null;
    }

    /**
     * 🗺️ จังหวัดเกิดที่จะใช้ผูกดวง — จังหวัดที่ระบบรู้แล้ว ชนะชื่อจังหวัดที่เจอในข้อความเสมอ
     *
     * ทำไมค่าที่รู้แล้วต้องชนะ: resolve() ไม่ต้องมีคำว่า "เกิด" นำหน้า (ยกเว้นชื่อกำกวมใน NEEDS_CUE)
     *   ⇒ คำถาม "จะได้ย้ายไปทำงานภูเก็ตไหม" ก็อ่านได้ว่าภูเก็ต ทั้งที่ไม่ใช่ที่เกิด
     *   ส่วนค่าที่รู้แล้ว (FortuneReading::birthProvinceIfKnown) มาจากคำตอบกล่อง "เกิดจังหวัดอะไร"
     *   / แอดมินกรอก / บิลเก่าของคนเดียวกัน — เชื่อได้กว่า
     *   (ลำดับเดียวกับ ThaiAstrologyService::buildCelticBirthAstrologyBlock)
     *
     * ⚠️ พรอมต์ดูดวง 39 ใบเดียวมีผังดวง 2 ทาง — ผังท้ายพรอมต์ (FortuneAIService::buildPrompt)
     *    กับช่อง {transit_info} (FortuneConversationService::getCurrentTransitDescription)
     *    ทั้งสองต้องเรียกเมธอดนี้ด้วยอินพุตชุดเดียวกัน ไม่งั้นลัคนาคนละราศี = ภพของดาวจรขัดกันเอง
     *
     * @param  string|null  $known  จังหวัดที่รู้แล้ว (null / ชื่อที่ไม่รู้จัก = ยังไม่รู้)
     * @param  string  $text  ข้อความลูกค้า — อ่านก็ต่อเมื่อยังไม่รู้จังหวัดเท่านั้น
     * @return string|null ชื่อจังหวัด · null = ไม่ทราบ (ผังใช้พิกัดกรุงเทพและบอกตามตรง)
     */
    public static function forChart(?string $known, string $text = ''): ?string
    {
        if (self::isKnown($known)) {
            return $known;
        }

        return self::resolve($text);
    }

    /**
     * ชื่อทางการ + ชื่อเรียกอื่น เรียง "ยาวก่อนสั้น" (คำนวณครั้งเดียวต่อโปรเซส)
     *
     * @return array<string, string>
     */
    private static function candidates(): array
    {
        static $sorted = null;
        if ($sorted !== null) {
            return $sorted;
        }

        $sorted = [];
        foreach (array_keys(self::PROVINCES) as $name) {
            $sorted[$name] = $name;
        }
        foreach (self::ALIASES as $alias => $official) {
            $sorted[$alias] = $official;
        }
        uksort($sorted, fn ($a, $b) => mb_strlen($b) <=> mb_strlen($a));

        return $sorted;
    }

    /**
     * ชื่อกำกวม (เลย/ตาก/...) — ผ่านได้เมื่อมีคำนำหน้าบอกสถานที่ หรือทั้งข้อความคือชื่อนั้น
     */
    private static function cueSatisfied(string $haystack, string $needle): bool
    {
        // ตอบสั้น ๆ ว่า "เลย" / "จ.เลย" ตอนแม่หมอเพิ่งถามจังหวัด = ชัดเจนอยู่แล้ว
        $bare = trim(str_replace(['จังหวัด', 'จ.', 'ครับ', 'ค่ะ', 'คะ', 'ครัช'], '', $haystack));
        if ($bare === $needle) {
            return true;
        }

        return (bool) preg_match('/'.self::CUE.preg_quote($needle, '/').'/u', $haystack);
    }

    /**
     * พิกัดของจังหวัด — ['lat' => float, 'lon' => float] · null = ไม่รู้จัก
     *
     * @return array{lat: float, lon: float}|null
     */
    public static function coords(?string $province): ?array
    {
        if ($province === null || $province === '') {
            return null;
        }

        $name = self::ALIASES[$province] ?? $province;
        if (! isset(self::PROVINCES[$name])) {
            return null;
        }

        return ['lat' => self::PROVINCES[$name][0], 'lon' => self::PROVINCES[$name][1]];
    }

    /** จังหวัดนี้มีในฐานหรือไม่ (รับชื่อเรียกอื่นด้วย) */
    public static function isKnown(?string $province): bool
    {
        return self::coords($province) !== null;
    }

    /**
     * 🕰️ "เวลาอัตโนมัติ" — ส่วนต่างระหว่างเวลานาฬิกากับเวลาสุริยคติท้องถิ่น (นาที)
     *
     * เวลามาตรฐานไทยอิงเส้นลองจิจูด 105°E ทั้งประเทศ แต่ดวงอาทิตย์ขึ้น-ตกจริงต่างกันตามพิกัด
     * ⇒ คนเกิดแม่ฮ่องสอน (97.97°E) นาฬิกาบอก 06:00 แต่ดวงอาทิตย์ยังอยู่ตำแหน่ง 05:32 ตามจริง
     * โหรไทยเรียกส่วนต่างนี้ว่า "เวลาอัตโนมัติ" และหักก่อนผูกดวงเสมอ
     *
     * ⚠️ ตัวเลขนี้ใช้ **แสดงผล/ตรวจสอบเท่านั้น ห้ามเอาไปบวกลบเวลาเกิดซ้ำ** —
     *    สูตรลัคนาของเราคำนวณ Local Sidereal Time จากลองจิจูดจริงอยู่แล้ว
     *    (lst = gmst + lon) ⇒ แก้ให้เรียบร้อยในตัวสูตร ถ้าหักอีกรอบ = ผิดสองเท่า
     *
     * @return float|null นาที (ลบ = ช้ากว่านาฬิกา) · null = ไม่รู้จักจังหวัด
     */
    public static function localMeanTimeOffsetMinutes(?string $province): ?float
    {
        $c = self::coords($province);
        if ($c === null) {
            return null;
        }

        // เส้นแวงอ้างอิงของเวลามาตรฐานไทย (UTC+7) = 105°E · 1° = 4 นาที
        return round(($c['lon'] - 105.0) * 4.0, 1);
    }

    /** ชื่อจังหวัดมาตรฐานทั้ง 77 (เรียงตามที่ประกาศ) */
    public static function all(): array
    {
        return array_keys(self::PROVINCES);
    }
