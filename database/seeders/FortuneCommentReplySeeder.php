        if (FortuneCommentReply::query()->exists()) {
            $this->command->info('มีคลังคำตอบอยู่แล้ว ข้าม...');

            return;
        }

        $sort = 0;

        foreach ($this->messages() as $category => $list) {
            foreach ($list as $message) {
                FortuneCommentReply::create([
                    'message' => $message,
                    'category' => $category,
                    'locale' => 'th',
                    'is_active' => true,
                    'sort_order' => $sort++,
                ]);
            }
        }

        $this->command->info('✅ Seed คลังคำตอบคอมเมนต์สำเร็จ! รวม '.FortuneCommentReply::count().' ชุด');
    }

