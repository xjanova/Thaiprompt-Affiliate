    public static function yesNoMultipliers(array $profile): ?array
    {
        $yn = $profile['yes_no'] ?? null;
        if ($yn === self::CELTIC) {
            return array_map('floatval', (array) config('fortune_yes_no_weights.position_multiplier', []));
        }

        return is_array($yn) ? $yn : null;
    }

