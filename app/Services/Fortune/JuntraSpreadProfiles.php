    public static function readingRules(array $profile): string
    {
        $out = ['── วิธีอ่านของแพ็กเกจนี้ ──', $profile['role']];
        foreach ($profile['rules'] as $r) {
            $out[] = "• {$r}";
        }

        return implode("\n", $out);
    }

