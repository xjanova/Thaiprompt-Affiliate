<?php

namespace App\Services\Fortune;

/**
 * 🛒 คำตอบตอน "เลือกแพคเกจ" นี้ = ลูกค้าเลือกแพคเกจจริง หรือแค่ประโยคที่บังเอิญมีคำของแพคเกจ
 *
 * ด่านเลือกแพคเกจ (handleTierChoice / handleFreeCardUpsellResponse) จับคำแบบ "มีอยู่ตรงไหนก็ได้"
 * ('39', 'ละเอียด', 'ปกติ', '99', 'บูชาครู' …) แล้วออกบิลทันที ⇒ ประโยคที่ **ถาม** หรือ **ผัดเวลา**
 * ก็กลายเป็นบิลที่ลูกค้าไม่ได้สั่ง (เจ้าของ 2026-11-09: "ทำไมดูฟรีเสร็จเปิดบิล 39 ให้เอง เฉยเลย")
 *
 * เคสจริงบน prod (FB · ไม่มีใบไหนจ่าย):
 *   #14558 FTU-261030-B3883  "…เดี๋ยวให้หนูกลับบ้านแล้วหนูจะดูให้ลูกทำให้ 39 บาทใช่ไหมคะเรื่องละ" → บิล 39
 *          ตามด้วย "หนูไม่ค่อยมีตังค์ค่ะหนูไม่สบาย" — หมดอายุ
 *   #14605 FTU-261102-P4011  "ถ้าดูเกี่ยวกับลายละเอียดครูหมอ ต้องโปรไหนคะ" → บิล 39 ('ละเอียด' ใน 'รายละเอียด')
 *   #14660 FTU-261108-T0522  "ผมจะดูกับแม่ครับแบบละเอียดและให้แมช่วยขอเวลาอีกไม่นานครับแม่" → บิล 39
 *          หลังลูกค้าบอก "ไว้คราวหน้า / ยังไม่สะดวก" มาแล้ว 3 รอบ — ลูกค้าต้องพิมพ์ขอยกเลิกเอง
 *
 * กติกา: มีคำของแพคเกจ + (เป็นคำถาม หรือ ผัดเวลา/ปฏิเสธ) = ยังไม่ได้เลือก → ห้ามออกบิล
 *   ให้ตกไปสาขา chitchat (AI ตอบคำถาม + เตือนวิธีเลือก) ลูกค้าพิมพ์ "39" / กดปุ่ม ก็ได้บิลทันทีเหมือนเดิม
 *   ⚠️ ทิศที่ผิดได้ต้องเป็นทาง "ไม่ออกบิล" เสมอ — พลาดแค่ต้องกดอีกครั้ง
 *      ส่วนบิลที่ไม่ได้สั่ง = ลูกค้าเสียความรู้สึก + เสี่ยงนับ strike บิลไม่จ่าย ([[rule_bill_timeout_3hr_troll_ban]])
 *
 * คลาสนี้ไม่แตะ DB / Cache / AI — เทสต์ได้ตรง ๆ (tests/Unit/Services/TierPickIntentTest.php)
 */
class TierPickIntent
{
    /**
     * คำผสมที่ "มีคำของแพคเกจซ่อนอยู่" แต่ไม่ได้แปลว่าเลือกแพคเกจ — ตัดออกก่อนจับคำ
     *
     * 'รายละเอียด' = ขอข้อมูล ไม่ใช่ "แบบละเอียด" · 'ผิดปกติ' = เล่าอาการ ไม่ใช่ "แบบปกติ"
     */
    private const MASKED_COMPOUNDS = [
        'รายละเอียด', 'ลายละเอียด', 'ละเอียดอ่อน',
        // ⚠️ ห้ามใส่ 'ปกติก็' — "ดูแบบปกติก็ได้ค่ะ" คือการเลือกแพคเกจ
        'ผิดปกติ', 'ไม่ปกติ', 'ตามปกติ', 'เป็นปกติ', 'ปกติแล้ว', 'ปกติจะ', 'กลับมาปกติ', 'ปกติดี',
    ];

    /** คำ/อนุภาคที่ทำให้ประโยคเป็นคำถาม (ภาษาพูด + สะกดผิดที่เจอบ่อย) */
    private const QUESTION_MARKERS = [
        '?', '？',
        'ไหม', 'มั้ย', 'มั๊ย', 'ม้าย', 'มัย', 'ไม๊', 'ป่าว', 'ปล่าว', 'เปล่า', 'รึเปล่า', 'หรือเปล่า',
        'หรอ', 'เหรอ', 'ยังไง', 'ยังงัย', 'อย่างไร', 'แบบไหน', 'อันไหน', 'โปรไหน', 'ไหน',
        'เท่าไหร่', 'เท่าไร', 'เท่าไหล่', 'เท่าใด', 'อะไร', 'กี่', 'ทำไม', 'ต่างกัน', 'แตกต่าง',
        'หรือว่า', 'หรือ',
    ];

    /**
     * คำธรรมดาที่ "มีอนุภาคคำถามซ่อนอยู่" — ตัดทิ้งก่อนหาคำถาม
     *   'เกี่ยว' มี 'กี่' · 'สมัย' มี 'มัย' · 'หรอก' มี 'หรอ'
     *   ("ขอดู 39 เกี่ยวกับความรักค่ะ" คือการเลือก ไม่ใช่คำถาม)
     */
    private const NOT_QUESTION_WORDS = ['เกี่ยว', 'สมัย', 'หรอก'];

    /**
     * "ขอ 39 ได้ไหมคะ" = ขอซื้อแบบสุภาพ ไม่ใช่ถามข้อมูล → ตัดท้าย "ได้ไหม" ทิ้งก่อนหาคำถาม
     *   เฉพาะเมื่อขึ้นต้นด้วยกริยาขอ/เลือก (ไม่งั้น "ดูเรื่องงานได้ไหม" ก็จะกลายเป็นการซื้อ)
     */
    private const POLITE_REQUEST_LEAD = '/^(ขอ|เอา|รับ|เลือก|จัด|สั่ง|ดู|อยากดู|อยากได้|สนใจ)/u';

    private const POLITE_REQUEST_TAIL = '/ได้(ไหม|มั้ย|มั๊ย|ม้าย|มัย|ป่าว|ปล่าว|เปล่า|รึเปล่า|หรือเปล่า|ไม๊)/u';

    /** ผัดเวลา / ยังไม่พร้อม / ปฏิเสธ — มีคำแพคเกจปนก็ยังไม่ใช่การเลือก */
    private const DEFER_PHRASES = [
        // ผัดเวลา
        'ไว้ก่อน', 'ไว้คราวหน้า', 'คราวหน้า', 'ไว้วันหลัง', 'วันหลัง', 'ทีหลัง', 'ภายหลัง', 'ไว้ทีหลัง',
        'ขอเวลา', 'รอก่อน', 'ยังก่อน', 'กลับบ้าน', 'ถ้าว่าง', 'ว่างแล้ว', 'ว่างเมื่อไหร่',
        // ⚠️ 'พรุ่งนี้' / 'มะรืน' เดี่ยว ๆ ไม่นับ — "ขอ 39 ดูงานพรุ่งนี้" คือการเลือก (ดู DEFER_REGEX)
        'สิ้นเดือน', 'ปลายเดือน', 'ต้นเดือน', 'เงินเดือนออก',
        'ขอคิด', 'คิดดูก่อน',
        // ยังไม่พร้อม (สะกดตามที่ลูกค้าพิมพ์จริง: "สดวก")
        // ⚠️ ห้ามใส่ 'ยังไม่มี' เดี่ยว ๆ — "ยังไม่มีแฟนค่ะ ขอดู 39" คือการเลือก
        'ยังไม่พร้อม', 'ไม่พร้อม', 'ไม่สะดวก', 'ไม่สดวก', 'ยังไม่ว่าง', 'ไม่ว่าง',
        'ยังไม่โอน', 'ยังไม่ได้โอน', 'ยังไม่จ่าย',
        // ไม่มีเงิน / ทำไม่ได้
        'ไม่มีเงิน', 'เงินไม่พอ', 'ไม่มีตัง', 'ไม่ค่อยมีตัง', 'ตังไม่พอ', 'ตังค์ไม่พอ', 'จ่ายไม่ได้', 'โอนไม่ได้',
        'ไม่มีบัญชี', 'ไมมีบัญชี', 'ไม่มีแอป', 'ทำไม่เป็น', 'ส่งไม่เป็น', 'โอนไม่เป็น',
        'แพงไป', 'ราคาแพง', 'ถ้าแพง',
        // ปฏิเสธ
        'ไม่เอา', 'ไม่ดู', 'ไม่สนใจ', 'ไม่ต้อง', 'ยังไม่ดู', 'ยังไม่เอา',
    ];

    /** "มีเงิน…ก่อน" / "เดี๋ยว…แล้วจะ" — ภาษาพูดแทรกคำกลางวลี */
    private const DEFER_REGEX = [
        '/มีเงิน.{0,16}ก่อน/u',
        '/ได้เงิน.{0,16}ก่อน/u',
        '/เงินเข้า.{0,16}ก่อน/u',
        // "เดี๋ยวให้หนูกลับบ้านแล้วหนูจะดู" · "เดี๋ยวว่างค่อยดู"
        '/เดี๋ยว.{0,30}(ค่อย|แล้วจะ|แล้วหนูจะ|แล้วผมจะ|แล้วค่อย)/u',
        '/(ไว้|ค่อย|เดี๋ยว).{0,12}(พรุ่งนี้|มะรืน|อาทิตย์หน้า|เดือนหน้า|วันหลัง)/u',
        '/(พรุ่งนี้|มะรืน|อาทิตย์หน้า|เดือนหน้า).{0,12}(ค่อย|จะโอน|ถึงจะ)/u',
    ];

    /**
     * ข้อความ (lowercase) ที่ตัดคำผสมหลอกออกแล้ว — ใช้จับคำแพคเกจแบบ substring ต่อ
     */
    public static function keywordText(string $text): string
    {
        $lower = mb_strtolower(trim($text));

        // แทนด้วยช่องว่าง ไม่ใช่สตริงว่าง — กันคำสองฝั่งต่อกันกลายเป็นคำใหม่
        return str_replace(self::MASKED_COMPOUNDS, ' ', $lower);
    }

    /**
     * มีราคา N เป็น "ตัวเลขเดี่ยว" ไหม — ไม่นับเลขที่เป็นส่วนหนึ่งของเลขอื่น
     *
     * 'เกิด 12/3/2539' / '0839xxxxxx' / 'ปี 1999' ต้องไม่กลายเป็นบิล 39 / 99
     */
    public static function mentionsPrice(string $text, int $price): bool
    {
        if ($price <= 0) {
            return false;
        }

        return preg_match('/(?<![0-9])'.$price.'(?![0-9])/u', $text) === 1;
    }

    /**
     * ประโยคนี้ "ยังไม่ใช่การเลือกแพคเกจ" ไหม (ถาม / ผัดเวลา / ปฏิเสธ)
     *
     * true = ห้ามออกบิลจากคำของแพคเกจในประโยคนี้
     */
    public static function isNotAPick(string $text): bool
    {
        return self::looksLikeQuestion($text) || self::looksDeferred($text);
    }

    public static function looksLikeQuestion(string $text): bool
    {
        $lower = mb_strtolower(trim($text));
        if ($lower === '') {
            return false;
        }

        $lower = str_replace(self::NOT_QUESTION_WORDS, ' ', $lower);

        if (preg_match(self::POLITE_REQUEST_LEAD, $lower) === 1) {
            $lower = (string) preg_replace(self::POLITE_REQUEST_TAIL, ' ', $lower);
        }

        foreach (self::QUESTION_MARKERS as $marker) {
            if (mb_strpos($lower, $marker) !== false) {
                return true;
            }
        }

        return false;
    }

    public static function looksDeferred(string $text): bool
    {
        $lower = mb_strtolower(trim($text));
        if ($lower === '') {
            return false;
        }

        foreach (self::DEFER_PHRASES as $phrase) {
            if (mb_strpos($lower, $phrase) !== false) {
                return true;
            }
        }

        foreach (self::DEFER_REGEX as $re) {
            if (preg_match($re, $lower) === 1) {
                return true;
            }
        }

        return false;
    }
}
