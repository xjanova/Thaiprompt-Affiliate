        //    ดาวจรลอย ๆ บอกได้แค่ว่าดาวอยู่ราศีไหน แต่สิ่งที่ทำให้ "ช่วงนี้" ต่างจาก "ช่วงอื่น"
        //    คือดาวจรไปทำมุมกับดาวในดวงกำเนิดของเจ้าชะตาคนนี้โดยเฉพาะ
        //    เอาเฉพาะดาวช้า (อาทิตย์ขึ้นไป) — จันทร์/พุธ/ศุกร์ เร็วเกิน ยิงมุมใหม่แทบทุกวัน = noise
        $out .= $this->formatTransitAspectLines($positions);

        $out .= "   🔒 *ระบุช่วงเวลาได้เฉพาะจากดาวจรชุดนี้* — ❌ ห้ามแต่งว่าดาวดวงใดจะย้ายเข้าภพไหนวันไหน\n"
            ."   ⏳ ความเร็วดาว (ใช้ประเมินว่าเรื่องจะกินเวลาแค่ไหน — ห้ามบอกวันที่เป๊ะเกินจริง):\n"
            ."      จันทร์ ~2 วันครึ่ง/ราศี · อาทิตย์-พุธ-ศุกร์ ~1 เดือน/ราศี · อังคาร ~6 สัปดาห์\n"
            // ☋ (2026-09-11) เกตุไทย (สุริยยาตร์) ราศีละ 56 วัน 14 ชม. — เร็วกว่าราหูเกือบ 10 เท่า
            //    เดิมเขียน "ราหู-เกตุ ~1 ปีครึ่ง" ซึ่งจริงเฉพาะเกตุอินเดียที่ผูกตรงข้ามราหู
            ."      พฤหัสบดี ~1 ปี · เสาร์ ~2 ปีครึ่ง · ราหู ~1 ปีครึ่ง · เกตุ ~2 เดือน (ราหู-เกตุเดินถอยหลังทั้งคู่)\n";

