     *   ตามด้วย "รายละเอียดการเกิดล้วน" (วันที่ เวลา เดือน วัน ปี ที่ จังหวัด) แล้วถึงชื่อจังหวัด
     *   ✅ "หนูเกิดเวลา 08:30 น. ที่เชียงใหม่" · "เกิด 15 พ.ค. 2533 ที่จังหวัดขอนแก่น" · "บ้านเกิดอยู่อุดร"
