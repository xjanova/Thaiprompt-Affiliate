        if (! Schema::hasTable('classroom_courses') || ! Schema::hasTable('classroom_questions')) {
            $this->command?->warn('ยังไม่มีตาราง classroom_* — ข้าม (รัน migrate ก่อน)');

            return;
        }

        $this->command?->info('🎓 กำลัง seed ห้องเรียน (คอร์ส 3 บทบาท + คลังข้อสอบ)...');

        foreach (self::courses() as $role => $course) {
            $model = ClassroomCourse::query()->where('role', $role)->orderBy('id')->first();
            if ($model === null) {
                $model = ClassroomCourse::create(array_merge($course['attributes'], [
                    'role' => $role,
                    'rules_version' => self::RULES_VERSION,
                    'is_active' => true,
                ]));
                $this->command?->info('  ✅ สร้างคอร์ส'.ClassroomCourse::ROLE_LABELS[$role]);
            }

            if (ClassroomQuestion::query()->where('course_id', $model->id)->exists()) {
                $this->command?->info('  ⏭️  คลังข้อสอบ'.ClassroomCourse::ROLE_LABELS[$role].'มีอยู่แล้ว ข้าม');

                continue;
            }

            foreach ($course['questions'] as [$question, $choices, $correct, $explanation]) {
                ClassroomQuestion::create([
                    'course_id' => $model->id,
                    'question' => $question,
                    'choices' => $choices,
                    'correct_index' => $correct,
                    'explanation' => $explanation,
                    'is_active' => true,
                ]);
            }
            $this->command?->info('  ✅ เพิ่มข้อสอบ'.ClassroomCourse::ROLE_LABELS[$role].' '.count($course['questions']).' ข้อ');
        }

        $this->command?->info('✅ Seed ห้องเรียนสำเร็จ!');
    }

