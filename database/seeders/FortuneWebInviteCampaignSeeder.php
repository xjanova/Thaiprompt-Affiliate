    /**
     * สร้างข้อความหมวดเชิญมาเว็บ
     */
    public function run(): void
    {
        $this->command?->info('🌱 กำลัง seed ข้อความหมวดเชิญมาเว็บ (150 แบบ)...');

        $created = self::seed();

        $this->command?->info($created > 0
