    protected function formatNatalAspectLines(array $positions, int $limit = 6, bool $hourKnown = true): string
    {
        if (! $hourKnown) {
            unset($positions['Moon']);
        }

        $aspects = AstroAspects::withinChart($positions);
        if (empty($aspects)) {
            return '';
        }

        $out = "   📐 มุมสัมพันธ์ในดวงกำเนิด (ใช้อ่านนิสัย/แรงปะทะภายใน — คำนวณจริง):\n";
        foreach (array_slice($aspects, 0, $limit) as $a) {
            $out .= "      {$a['a']} {$a['name']} {$a['b']} (คลาด {$a['orb']}°) — {$a['nature']}\n";
        }

        return $out;
    }

    /**
     * 🌙 จันทร์อยู่ราศีอะไรตลอดวันนั้น — และย้ายราศีระหว่างวันหรือเปล่า
     *
     * จันทร์เดิน ~13°/วัน ⇒ ราว 43% ของวันจะมีการย้ายราศี
     * ถ้าย้าย แปลว่า "ไม่รู้เวลาเกิด = ไม่รู้ราศีจันทร์" ⇒ จันทร์ลัคน์ก็ใช้ไม่ได้ ต้องยอมรับตรง ๆ
     *
     * @return array{crosses: bool, sign: string|null, from: string|null, to: string|null}
     */
    protected function moonSignSpanForDay(\Carbon\Carbon $date): array
    {
        try {
            $eph = new PlanetEphemeris;
            $start = $eph->positions($date->copy()->setTime(0, 0, 0))['Moon'] ?? null;
            $end = $eph->positions($date->copy()->setTime(23, 59, 0))['Moon'] ?? null;
        } catch (\Throwable $e) {
            return ['crosses' => true, 'sign' => null, 'from' => null, 'to' => null];
        }

        if ($start === null || $end === null) {
            return ['crosses' => true, 'sign' => null, 'from' => null, 'to' => null];
        }

        $crosses = ($start['sign'] ?? null) !== ($end['sign'] ?? null);

        return [
            'crosses' => $crosses,
            'sign' => $crosses ? null : (string) $start['sign'],
            'from' => (string) ($start['sign'] ?? ''),
            'to' => (string) ($end['sign'] ?? ''),
        ];
    }

    /**
