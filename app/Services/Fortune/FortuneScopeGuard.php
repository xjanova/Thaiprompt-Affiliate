    /**
     * ตัดตัวบทสวด/คาถาออกจากคำตอบ AI
     *
     * ⚠️ (จับผี #3) **ตัดเป็น "ช่วง" ไม่ใช่ทั้งบรรทัด** —
     *    ของเดิมลบทั้งบรรทัด ⇒ บรรทัด "🙏 ทำเองที่บ้านก่อน — นะโม ตัสสะ ..." หายยกบรรทัด
     *    ลูกค้าเสียทั้งหัวข้อและคำแนะนำ แล้ว **ด่าน must ของ Celtic (🙏) ก็หายไปด้วย**
     *    ⇒ ตอนนี้ตัดตั้งแต่จุดที่บทสวดเริ่ม เก็บหัวข้อ/เนื้อความก่อนหน้าไว้เสมอ
     *
     * ⚠️ (จับผี #3) หมายเหตุท้ายข้อความ **ห้ามมีอีโมจิ** — ของเดิมขึ้นต้นด้วย 🙏
     *    ซึ่งเป็นอีโมจิบังคับ (`'must' => ['🙏']`) ของเซคชั่น "ทางแก้" เลยคุณไสย
     *    ⇒ เซคชั่นที่ลูกค้าจ่าย 99฿ มาซื้อหายไป แต่ด่านรายงานว่า "ผ่าน" เงียบ ๆ
     *    ([[rule_must_gate_no_foreign_emoji_in_spec]])
     *
     * @param  string  $reply  คำตอบจาก AI
     * @return array{text: string, stripped: bool} ข้อความที่ล้างแล้ว + เจอบทสวดไหม
     */
    public static function stripChantText(string $reply): array
    {
        if (trim($reply) === '') {
            return ['text' => $reply, 'stripped' => false];
        }

        $lines = preg_split('/\R/u', $reply) ?: [];
        $stripped = false;
        $out = [];

        foreach ($lines as $line) {
            $cut = self::truncateAtChant($line);
            if ($cut === null) {
                $out[] = $line;

                continue;
            }

            $stripped = true;
            if (trim($cut) !== '') {
                $out[] = $cut;   // เก็บหัวข้อ/เนื้อความก่อนหน้าบทสวดไว้
            }
        }

        if (! $stripped) {
            return ['text' => $reply, 'stripped' => false];
        }

        $text = preg_replace("/\n{3,}/u", "\n\n", implode("\n", $out)) ?? implode("\n", $out);
        $text = trim($text);

        // ❌ ห้ามมีอีโมจิในหมายเหตุ — จะไปหลอกด่าน must ของ Celtic
        $notice = '(บทสวดเต็ม ๆ แม่หมอไม่ท่องให้ผ่านตัวหนังสือนะลูก '
            .'ขาดคำแล้วความหมายเพี้ยน — เปิดจากหนังสือสวดมนต์ หรือขอจากพระที่วัดเอา แล้วสวดให้ครบบท)';

        return [
            'text' => $text === '' ? $notice : $text."\n\n".$notice,
            'stripped' => true,
        ];
    }

    /**
     * หาจุดที่ "ตัวบทสวด" เริ่มในบรรทัดนี้ แล้วคืนข้อความส่วนที่อยู่ก่อนหน้า
     *
     * @return string|null null = บรรทัดนี้ไม่มีบทสวด (ไม่ต้องแตะ)
     */
    protected static function truncateAtChant(string $line): ?string
    {
        if (trim($line) === '') {
            return null;
        }

        $cutAt = null;

        // A. คำเปิดบทที่รู้จัก — ตัดตั้งแต่ตำแหน่งที่เจอ
        $lower = mb_strtolower($line);
        foreach (self::CHANT_MARKERS as $marker) {
            $pos = mb_strpos($lower, mb_strtolower($marker));
            if ($pos !== false && ($cutAt === null || $pos < $cutAt)) {
                $cutAt = $pos;
            }
        }

        // B. ความหนาแน่นพยางค์บาลี — ตัดตั้งแต่พยางค์บาลีตัวแรกของช่วงที่หนาแน่น
        if ($cutAt === null) {
            $densityAt = self::paliRunOffset($line);
            if ($densityAt !== null) {
                $cutAt = $densityAt;
            }
        }

        if ($cutAt === null) {
            return null;
        }

        $kept = mb_substr($line, 0, $cutAt);

        // เก็บกวาดตัวคั่นที่ค้างท้าย ("— " / ": " / "ว่า " / วงเล็บเปิด)
        $kept = preg_replace('/[\s\-–—:：("“\'‘]*(?:ว่า|ดังนี้|คือ|ตามนี้)?[\s\-–—:：("“\'‘]*$/u', '', $kept) ?? $kept;

        return rtrim($kept);
    }

    /**
     * หา offset ของพยางค์บาลีตัวแรก เมื่อบรรทัดนี้มีพยางค์บาลี ≥4 คำ
     *
     * @return int|null null = ไม่หนาแน่นพอ
     */
    protected static function paliRunOffset(string $line): ?int
    {
        if (! preg_match_all('/[^\s๚๛ฯ]+/u', $line, $m, PREG_OFFSET_CAPTURE)) {
            return null;
        }
        $tokens = $m[0];
        if (count($tokens) < 4) {
            return null;
        }

        $paliCount = 0;
        $firstOffsetBytes = null;

        foreach ($tokens as [$raw, $byteOffset]) {
            $token = trim($raw, " \t\n\r\0\x0B.,;:!?()[]{}\"'“”‘’-–—•*");
            if ($token === '' || mb_strlen($token) < 2) {
                continue;
            }
            if (in_array($token, self::PALI_LOOKALIKE_STOPWORDS, true)) {
                continue;
            }
            if (! preg_match('/^[\p{Thai}]+$/u', $token)) {
                continue;
            }
            if (preg_match('/(ะ|ัง|ุง|โต|โน|โส|ตุ|มิ|สิ|นัง|ตัง|ยะ|วา|ตี|นโต)$/u', $token)) {
                $paliCount++;
                if ($firstOffsetBytes === null) {
                    $firstOffsetBytes = $byteOffset;
                }
            }
        }

        if ($paliCount < 4 || $firstOffsetBytes === null) {
            return null;
        }

        // แปลง byte offset → character offset (mb_substr ใช้หน่วยตัวอักษร)
        return mb_strlen(substr($line, 0, $firstOffsetBytes));
    }
