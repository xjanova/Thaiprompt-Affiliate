<?php

namespace App\Services\Fortune;

/**
 * 📘 กฎกลางของ "คอนเทนต์อัตโนมัติที่โพสลง Facebook"
 *
 * เจ้าของสั่ง (2026-08-01): "ห้ามใช้อีโมจิ และห้ามใช้แฮชแท็กเกิน 3 อัน"
 *
 * ⚠️ ทำไมต้องรวมไว้คลาสเดียว:
 *   ระบบมีจุดประกอบ caption ลง FB **4 จุด** (แคมเปญคอนเทนต์ / สายมู / ดวงรายวันรวมโพส /
 *   ดวงรายวันรายวันเกิด) ถ้าไปแก้กระจายทีละไฟล์ อีกหกเดือนจะเหลือจุดที่ยังพ่นอีโมจิอยู่
 *   แล้วหาไม่เจอ — กฎแบรนด์ต้องมีสวิตช์เดียว
 *
 * ⚠️ ทำไมต้อง "ลบทีหลัง" ไม่ใช่แค่สั่งใน prompt:
 *   prompt เป็นแค่คำขอ — โมเดลใส่อีโมจิกลับมาเป็นประจำแม้สั่งห้ามชัด ๆ
 *   และ caption บางส่วนไม่ได้มาจาก AI เลย (fallback template / เทมเพลตที่แอดมินพิมพ์เอง /
 *   อีโมจิประจำวันเกิดที่ฝังในโค้ด) → ต้องมีด่านกวาดท้ายทางเสมอ
 */
class FacebookContentPolicy
{
    /** จำนวนแฮชแท็กสูงสุดต่อโพส (เจ้าของกำหนด — เกินนี้ถูกตัดทิ้งไม่ว่าตั้งค่าไว้เท่าไร) */
    public const MAX_HASHTAGS = 3;

    /**
     * ช่วงอักขระที่ถือว่าเป็น "อีโมจิ/สัญลักษณ์ประดับ"
     *
     * 🚨 จงใจ**ไม่**รวม:
     *   - U+2500-257F Box Drawing — เส้นคั่น ━━━ ในโพสดวงรายวันต้องอยู่ครบ
     *   - U+2000-206F General Punctuation — — … " " ต้องไม่โดนลบ
     *   - U+3010/3011 【】 — วงเล็บหัวข้อคนเกิดวัน
     *   - ตัวอักษรไทย U+0E00-0E7F
     */
    private const EMOJI_PATTERN = '/[\x{1F000}-\x{1FAFF}'   // emoji หลักทั้งหมด (รวมธง สัตว์ อาหาร)
        .'\x{1F1E6}-\x{1F1FF}'                              // regional indicator (ธงชาติ)
        .'\x{2600}-\x{27BF}'                                // ☀ ✨ ❤ ✔ ➡
        .'\x{2B00}-\x{2BFF}'                                // ⭐ ⬆
        .'\x{2300}-\x{23FF}'                                // ⏰ ⌛ ⏳
        .'\x{25A0}-\x{25FF}'                                // ▪ ● ◆ (รูปทรงประดับ)
        .'\x{2190}-\x{21FF}'                                // ← ↑ → ↓
        .'\x{FE00}-\x{FE0F}'                                // variation selector (ตัวทำให้เป็นสี)
        .'\x{200D}'                                         // ZWJ (ต่ออีโมจิผสม)
        .'\x{20E3}'                                         // keycap (ตัวประกอบ 1️⃣)
        .']/u';

    /**
     * กฎห้ามอีโมจิที่ฉีดเข้า prompt ของ AI — ด่านแรก (ด่านสองคือ clean() กวาดของที่หลุดมา)
     *
     * 🚨 มีแค่เรื่องอีโมจิเท่านั้นโดยตั้งใจ — เพดานแฮชแท็กบังคับด้วย **โค้ด**
     *    (capHashtags / capHashtagsInText) ไม่ใช่คำขอใน prompt เพราะแต่ละ service
     *    มีกฎแฮชแท็กของตัวเองอยู่แล้ว (บางตัวสั่ง "ห้ามใส่เลย ระบบเติมให้")
     *    ใส่ซ้ำเข้าไปจะกลายเป็นคำสั่งขัดกันเอง — "ห้ามใส่" กับ "ใส่ได้ 3" ในโพสเดียว
     *
     * @return string บรรทัดกฎภาษาไทย (มี \n ปิดท้าย พร้อมต่อในรายการกฎ)
     */
    public static function noEmojiRule(): string
    {
        return "ห้ามใช้อีโมจิ (emoji) เด็ดขาด — ไม่ว่าจะหัวข้อ กลางเนื้อหา หรือท้ายโพส ใช้ตัวอักษรล้วนเท่านั้น\n";
    }

    /**
     * 🚫 "engagement bait" — ประโยคขอให้คนอ่านกดไลก์/แชร์/แท็ก/คอมเมนต์
     *
     * 🚨 (2026-09-05) เจ้าของสั่ง "ถอด" หลังตรวจพบว่ามันเข้ามา **2 ทาง**:
     *   1. `text_prompt_template` ของแคมเปญใน DB สั่ง AI ตรง ๆ ว่า
     *      "เขียนให้คนอ่านอยากแท็กเพื่อนที่เกิดวัน…" ⇒ คำทำนายจริงลงท้ายด้วย
     *      "แท็กเพื่อนคนเกิดวันพุธให้มาเช็กดวงวันนี้" (4-5 ก.ย. เจอทุกวัน)
     *   2. `FortuneHoroscopeCampaign::generateEngagementHook()` ต่อท้ายโพสอีกชั้น
     *
     *   Meta ลดการมองเห็นโพสที่ขอ engagement — และผลกระทบไม่ได้จำกัดแค่โพสนั้น
     *   แต่กดทั้งเพจ ซึ่งเป็นต้นทางของลูกค้าทุกรายในระบบ
     *
     * ⚠️ ทำไมต้องกวาดที่นี่ ไม่ใช่แก้แค่ prompt/DB:
     *   template อยู่ใน DB ที่แอดมินแก้ทับได้ ([[rule_db_prompt_overrides_code]])
     *   และโมเดลเขียนเองได้แม้ไม่มีใครสั่ง (4 ก.ย. บางใบลงท้ายว่า
     *   "ถ้าถูกใจ ฝากส่งต่อให้เพื่อนที่เกิดวันอาทิตย์มาลองดูดวงด้วย" ทั้งที่ template
     *   ไม่ได้สั่งคำนั้น) ⇒ ต้องมีด่านกวาดท้ายทางเหมือนกฎอีโมจิ
     *
     * 🎯 คัดเฉพาะ "คำสั่งให้ผู้อ่านลงมือทำ" เท่านั้น ห้ามกว้างกว่านี้ —
     *   คำว่า "แชร์"/"ชวนเพื่อน" ลอย ๆ โผล่ในคำทำนายจริงได้ ("เหมาะกับการแชร์
     *   ความรู้สึกกับคนรัก" / "ชวนเพื่อนไปทำบุญ") ตัดทิ้งเท่ากับกินเนื้อคำทำนาย
     */
    private const ENGAGEMENT_BAIT_RE = '/(?:'
        .'แท[็๊]?กเพื่อน'
        .'|กด(?:ไลค์|ไลก์|ไลท์|ถูกใจ|แชร์|ติดตาม|หัวใจ|เลิฟ)'
        .'|(?:ช่วย|ฝาก|ขอ)?แชร์(?:ต่อ|ให้เพื่อน|โพสต?์|ให้หน่อย)'
        .'|(?:ฝาก)?ส่งต่อให้เพื่อน'
        .'|(?:คอมเมนต์|คอมเม้น|คอมเม้นท์|เม้น)(?:บอก|ไว้|ใต้โพส)'
        .'|พิมพ์ชื่อคนที่เกิด'
        .'|ชวนเพื่อน[^\n]{0,20}(?:มาดู|มาเช็ก|มาเช็ค|มาลอง|ดูดวง)'
        .')/u';

    /**
     * กฎห้ามขอ engagement ที่ฉีดเข้า prompt — ด่านแรก (ด่านสองคือ stripEngagementBait)
     */
    public static function noEngagementBaitRule(): string
    {
        return 'ห้ามขอให้คนอ่านกดไลก์ กดแชร์ แท็กเพื่อน คอมเมนต์ หรือส่งต่อโพสเด็ดขาด '
            ."(Facebook ลดการมองเห็นทั้งเพจ ไม่ใช่แค่โพสนั้น)\n"
            ."ปิดท้ายด้วยเนื้อคำทำนายหรือข้อแนะนำเท่านั้น\n";
    }

    /**
     * ลบ "บรรทัด" ที่มีคำขอ engagement ออกทั้งบรรทัด
     *
     * ⚠️ ตัดทั้งบรรทัดโดยตั้งใจ — ประโยคขอไลก์/แชร์อยู่บรรทัดของตัวเองเสมอในของจริง
     *   (ทั้งที่ AI เขียนเองและที่ generateEngagementHook ต่อท้าย) การตัดครึ่งประโยค
     *   จะเหลือเศษที่อ่านไม่รู้เรื่องแทน
     */
    public static function stripEngagementBait(string $text): string
    {
        $lines = preg_split('/\R/u', $text) ?: [];

        $kept = array_filter(
            $lines,
            fn ($line) => preg_match(self::ENGAGEMENT_BAIT_RE, $line) !== 1
        );

        $out = implode("\n", $kept);

        return trim(preg_replace('/\n{3,}/u', "\n\n", $out) ?? $out);
    }

    /** ข้อความนี้มีคำขอ engagement อยู่ไหม (ใช้ตรวจ/เทสต์ ไม่ได้แก้ข้อความ) */
    public static function hasEngagementBait(string $text): bool
    {
        return preg_match(self::ENGAGEMENT_BAIT_RE, $text) === 1;
    }

    /**
     * ตัดแฮชแท็ก "ที่ปนอยู่ในเนื้อหา" ให้เหลือไม่เกินเพดาน (อันที่เกินถูกลบทิ้ง)
     *
     * ใช้กับ caption ที่ AI เขียนแฮชแท็กเองในเนื้อ ไม่ใช่แบบที่ระบบเติมท้ายให้
     */
    public static function capHashtagsInText(string $text): string
    {
        $seen = 0;

        return preg_replace_callback(
            '/#[^\s#]+/u',
            function (array $m) use (&$seen) {
                $seen++;

                return $seen <= self::MAX_HASHTAGS ? $m[0] : '';
            },
            $text
        ) ?? $text;
    }

    /**
     * ตัดแฮชแท็กให้เหลือไม่เกินเพดาน
     *
     * @param  array<int, string>  $hashtags
     * @return array<int, string>
     */
    public static function capHashtags(array $hashtags): array
    {
        return array_slice(array_values($hashtags), 0, self::MAX_HASHTAGS);
    }

    /**
     * ตัดแฮชแท็กจาก "บรรทัดเดียวที่ประกอบมาแล้ว" (เช่น generateSmartHashtags ที่คืน string)
     *
     * แยกด้วยช่องว่าง แล้วเก็บเฉพาะโทเคนที่ขึ้นต้นด้วย # — โทเคนอื่นทิ้ง
     * (บรรทัดแฮชแท็กไม่ควรมีข้อความอื่นปน)
     */
    public static function capHashtagLine(string $line): string
    {
        $tokens = preg_split('/\s+/u', trim($line), -1, PREG_SPLIT_NO_EMPTY) ?: [];

        $tags = array_values(array_filter(
            $tokens,
            fn ($t) => str_starts_with($t, '#') && mb_strlen($t) > 1
        ));

        return implode(' ', self::capHashtags($tags));
    }

    /**
     * ลบอีโมจิออกจากข้อความ (ไม่จัดระเบียบช่องว่าง — ใช้ clean() ถ้าต้องการครบ)
     */
    public static function stripEmoji(string $text): string
    {
        // keycap (1️⃣ #️⃣) ประกอบจาก "ตัวอักษรธรรมดา + FE0F + 20E3"
        //   - ตัวเลข: ลบเฉพาะส่วนที่ทำให้เป็นอีโมจิ **เก็บเลขไว้** → "1️⃣ ข้อแรก" = "1 ข้อแรก"
        //     (ลบทั้งตัวจะเสียเลขข้อไปเปล่า ๆ ทั้งที่เลขไม่ใช่อีโมจิ)
        //   - # กับ *: ลบทั้งตัว เพราะเหลือไว้ก็ลอยไม่มีความหมาย และ # เดี่ยว ๆ
        //     ทำให้คนเข้าใจผิดว่าเป็นแฮชแท็กที่พิมพ์ตกด้วย
        $text = preg_replace('/[#*]\x{FE0F}?\x{20E3}/u', '', $text) ?? $text;

        return preg_replace(self::EMOJI_PATTERN, '', $text) ?? $text;
    }

    /**
     * 🧹 ด่านกวาดท้ายทาง — ลบอีโมจิ + เก็บกวาดร่องรอยที่มันทิ้งไว้
     *
     * ลบอีโมจิเฉย ๆ ไม่พอ เพราะจะเหลือ:
     *   - ช่องว่างค้างหน้าบรรทัด ("☀️ 【คนเกิดวัน...】" → " 【คนเกิดวัน...】")
     *   - ช่องว่างซ้อนกลางบรรทัด
     *   - บรรทัดที่เคยมีแต่อีโมจิ กลายเป็นบรรทัดว่างลอย
     *
     * เก็บย่อหน้า (บรรทัดว่าง 1 บรรทัด) ไว้เสมอ — โพส FB ที่ติดกันพืดคนไม่อ่าน
     */
    public static function clean(string $text): string
    {
        $text = self::stripEmoji($text);

        // 🚫 (2026-09-05) กวาดคำขอไลก์/แชร์/แท็ก ออกด้วย — เหตุผลเดียวกับอีโมจิเป๊ะ:
        //    prompt เป็นแค่คำขอ · template อยู่ใน DB ที่แก้ทับได้ · โมเดลเขียนเองได้
        //    วางไว้ใน clean() เพื่อให้ครอบจุดประกอบ caption ทั้ง 4 จุดด้วยสวิตช์เดียว
        $text = self::stripEngagementBait($text);

        $lines = preg_split('/\R/u', $text) ?: [];
        $lines = array_map(
            fn ($line) => trim(preg_replace('/[ \t]{2,}/u', ' ', $line) ?? $line),
            $lines
        );

        $text = implode("\n", $lines);
        $text = preg_replace('/\n{3,}/u', "\n\n", $text) ?? $text;

        return trim($text);
    }
}
