     * @param  array<int,array<string,mixed>>  $cards  key = ตำแหน่ง (จาก normaliseCards ของ controller)
     * @param  array<int,string>  $months  ชื่อเดือนจริงของแพ็กเกจ 12 เดือน (index 0 = ใบที่ 1)
     * @param  array{knowledge?:string, yes_no?:string, birth?:string}  $blocks
     */
    public static function userPrompt(array $profile, array $cards, string $question, array $months = [], array $blocks = []): string
    {
        $n = count($cards);
        $q = trim($question);
        $out = [];

        $out[] = '[กฎเหล็กการอ่านไพ่ — card-first]';
        $out[] = '1. ไพ่ที่ลูกเปิดได้ × ตำแหน่งของมัน = แหล่งความจริงเดียว ทุกข้อสรุปต้องบอกได้ว่ามาจากไพ่ใบไหน ตำแหน่งไหน';
        $out[] = '2. ไพ่ใบเดียวกันคนละตำแหน่งต้องให้คำตอบคนละแบบ · ตั้งตรง/กลับหัวต้องเปลี่ยนคำทำนายจริง';
        $out[] = '3. ❌ ห้ามประโยคที่จริงกับทุกคน ("อยู่ที่ใจเรา / แล้วแต่กรรม") — เอาไปแปะดวงคนอื่นได้ = ไม่ได้มาจากไพ่ → ตัดทิ้ง';
        $out[] = '4. ฟันธงตามไพ่ ไพ่เตือนก็เตือนตรง ๆ แต่ห้ามขายความกลัวหรือปั้นเรื่องร้ายที่ไพ่ไม่ได้บอก';
        $out[] = '5. '.self::NO_SOURCE_TALK;
        $out[] = '';
        $out[] = '── ข้อมูลการเปิดไพ่ ──';
        $out[] = "แพ็กเกจ: {$profile['title']} ({$n} ใบ)";
        $out[] = $q !== '' ? "คำถามของลูก: \"{$q}\"" : 'ลูกไม่ได้ระบุคำถาม — อ่านภาพรวมตามจุดประสงค์ของแพ็กเกจ';
        $out[] = 'ไพ่ตามตำแหน่ง:';
        $i = 0;
        foreach ($cards as $pos => $c) {
            $month = $months[$i] ?? null;
            $i++;
            $head = "• ใบที่ {$pos} — ".($c['position_name'] ?? "ตำแหน่ง {$pos}");
            if ($month) {
                $head .= " [เดือน: {$month}]";
            }
            if (! empty($c['position_description'])) {
                $head .= " [ตำแหน่งนี้ถาม: {$c['position_description']}]";
            }
            $out[] = $head;
            $name = trim(($c['card_name_th'] ?? '').(! empty($c['card_name_en']) ? " ({$c['card_name_en']})" : ''));
            $out[] = "   ไพ่: {$name} — ".(! empty($c['is_reversed']) ? 'กลับหัว' : 'ตั้งตรง');
            if (! empty($c['meaning'])) {
                $out[] = '   ความหมายพื้นฐาน: '.mb_substr((string) $c['meaning'], 0, 400);
            }
        }

        $out[] = '';
        $out[] = self::readingRules($profile);

        foreach (['yes_no', 'birth', 'knowledge'] as $b) {
            if (! empty($blocks[$b])) {
                $out[] = '';
                $out[] = trim($blocks[$b]);
            }
        }

        $out[] = '';
        $out[] = '── รูปแบบคำตอบ (ต้องตรงทุกหัวข้อ ตามลำดับนี้ · ขึ้นบรรทัดใหม่ก่อนทุกหัวข้อ) ──';
        $out[] = self::formatSpec($profile, $cards, $months, $q !== '', ! empty($blocks['birth']));
        $out[] = '';
        $out[] = "ความยาว: {$profile['length']} · ภาษาไทยล้วน · เรียกลูกค้าว่า \"".self::customerWord($profile).'"';

        return implode("\n", $out);
    }

    /**
     * สเปกหัวข้อคำตอบของแพ็กเกจ — หัวข้อทุกตัวต้องขึ้นต้นด้วย "## "
     */
    public static function formatSpec(array $profile, array $cards, array $months, bool $hasQuestion, bool $hasBirth): string
    {
        $h = self::HEADINGS;
        $lines = [];
        foreach ($profile['sections'] as $section) {
            switch ($section) {
                case 'verdict':
                    $verdictLine = $profile['key'] === 'decision'
                        ? '"ผล: เลือกทางเลือกที่ 1" หรือ "ผล: เลือกทางเลือกที่ 2"'
                        : ($hasQuestion && self::yesNoMultipliers($profile) !== null
                            ? '"ผล: ใช่" / "ผล: ไม่ใช่" / "ผล: ยังไม่ใช่ตอนนี้" (เลือกหนึ่ง ตามตาชั่งและไพ่)'
                            : '"ผล: <สรุปเรื่องเด่นใน 3-6 คำ>"');
                    $lines[] = "## {$h['verdict']}\nบรรทัดแรก {$verdictLine} แล้วตามด้วยคำฟันธง 1-3 ประโยค";
                    break;
                case 'cards':
                    foreach ($cards as $pos => $c) {
                        $label = $c['position_name'] ?? "ตำแหน่ง {$pos}";
                        $lines[] = "## {$h['card']} {$pos} · {$label}\nคำทำนายของไพ่ใบนี้ในตำแหน่งนี้สำหรับลูกคนนี้";
                    }
                    break;
                case 'months':
                    foreach (array_values($months) as $i => $m) {
                        $lines[] = "## {$h['month']} {$m} · <ดี|กลาง|ระวัง>\nบรรทัดแรก \"ธีม: <วลีสั้น>\" แล้ว 2-3 ประโยค (จากไพ่ใบที่ ".($i + 1).')';
                    }
                    break;
                case 'hearts':
                    $lines[] = "## {$h['hearts']}\nสองบรรทัดเท่านั้น: \"ใจเรา: ...\" และ \"ใจเขา: ...\" (อย่างละ 1 ประโยค จากใบที่ 1 และใบที่ 2)";
                    break;
                case 'story':
                    $lines[] = "## {$h['story']}\nร้อยไพ่ทุกใบเป็นเรื่องเดียวกัน 1-2 ย่อหน้า".($hasQuestion ? ' และตอบคำถามของลูกให้ชัด' : '');
                    break;
                case 'timing':
                    $lines[] = "## {$h['timing']}\n1-3 บรรทัด: ช่วงเวลาที่เรื่องจะขยับ/สุกงอม ตามที่ไพ่บอก (บอกเป็นช่วง ไม่ต้องเจาะวัน)";
                    break;
                case 'options':
                    foreach ([1, 2] as $o) {
                        $lines[] = "## {$h['option']} {$o}\nชื่อทางเลือกสั้น ๆ 1 บรรทัด แล้ว \"ข้อดี: ...\" \"ข้อควรระวัง: ...\" \"ผลที่ตามมา: ...\" อย่างละบรรทัด";
                    }
                    break;
                case 'choice':
                    $lines[] = "## {$h['choice']}\nบรรทัดแรก \"เลือก: ทางเลือกที่ 1\" หรือ \"เลือก: ทางเลือกที่ 2\" แล้วเหตุผลจากไพ่ 2-3 ประโยค";
                    break;
                case 'golden':
                    $lines[] = "## {$h['golden']}\n2 บรรทัด รูปแบบ \"- <ชื่อเดือน>: <เหตุผลสั้น>\"";
                    break;
                case 'caution':
                    $lines[] = "## {$h['caution']}\n2 บรรทัด รูปแบบ \"- <ชื่อเดือน>: <สิ่งที่ต้องระวัง>\"";
                    break;
                case 'birth':
                    if ($hasBirth) {
                        $lines[] = "## {$h['birth']}\n2-4 ประโยค: ดวงวันเกิดหนุนหรือถ่วงคำตอบของไพ่ตรงไหน (สรุปผล ไม่บรรยายการคำนวณ)";
                    }
                    break;
                case 'diagnosis':
                    $lines[] = "## {$h['diagnosis']}\nบรรทัดข้อมูลตามนี้ทุกบรรทัด (ไม่รู้ = ใส่ \"—\"):\n"
                        ."พบของ: <ใช่|ไม่ใช่|ไม่ชัด>\nชนิด: ...\nความรุนแรง: <หนัก|กลาง|เบา|—>\nลักษณะผู้ทำ: ...\nช่วงเวลา: ...\nมาทางทิศ: ...\nมูลเหตุ: ...\nเกราะคุ้มครอง: ...\n"
                        .'แล้วตามด้วยคำวินิจฉัย 2-3 ประโยค';
                    break;
                case 'detail':
                    $lines[] = "## {$h['detail']}\n1-2 ย่อหน้า: โดนอะไร ใครทำ (ลักษณะ) เพราะอะไร มาอย่างไร — อ่านตามไพ่เท่านั้น";
                    break;
                case 'remedy':
                    $lines[] = "## {$h['remedy']}\nรายการ \"- ...\" 3-5 ข้อ ทำเองได้จริง เรียงจากทำเองที่บ้านไปหาพึ่งพระ";
                    break;
                case 'direction':
                    $lines[] = $hasBirth
                        ? "## {$h['direction']}\n1-3 บรรทัด: ทิศที่ควรหันหน้าตอนสวด/ลอยเคราะห์/ตักบาตร จากดาวเจ้าชนะวันเกิดของลูก"
                        : "## {$h['direction']}\n1 บรรทัด: บอกว่าถ้าลูกกรอกวันเกิดตอนเปิดไพ่ แม่หมอจะคำนวณทิศสะเดาะเคราะห์ให้ได้ (ไม่ต้องเดาทิศ)";
                    break;
                case 'safety':
                    $lines[] = "## {$h['safety']}\n(ใส่เฉพาะเมื่อไพ่ชี้ว่าหนักถึงขั้นอันตราย — ไม่เข้าเกณฑ์ให้ข้ามหัวข้อนี้ไปเลย)";
                    break;
                case 'advice':
                    $lines[] = "## {$h['advice']}\nรายการ \"- ...\" 2-4 ข้อ ที่งอกมาจากไพ่ ลงมือได้จริง";
                    break;
            }
        }

        return implode("\n\n", $lines);
    }
