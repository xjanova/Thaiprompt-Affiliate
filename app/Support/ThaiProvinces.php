    /**
     * หาชื่อจังหวัดในข้อความ — คืนชื่อมาตรฐาน หรือ null ถ้าไม่พบ
     *
     * @param  string  $text  ข้อความจากลูกค้า
     */
    public static function resolve(string $text): ?string
    {
        $text = trim($text);
        if ($text === '') {
            return null;
        }

        // ทำความสะอาดเบา ๆ — ยุบวรรคซ้ำ ไม่แตะตัวอักษรไทย (ห้าม trim ทีละไบต์)
        $haystack = preg_replace('/\s+/u', ' ', $text) ?? $text;

        foreach (self::candidates() as $needle => $official) {
            if (mb_strpos($haystack, $needle) === false) {
                continue;
            }

            if (in_array($needle, self::NEEDS_CUE, true)
                && ! self::cueSatisfied($haystack, $needle)) {
                continue;
            }

            return $official;
        }

        return null;
    }

