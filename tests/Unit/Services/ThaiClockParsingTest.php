        parent::setUp();
        // constructor ดึง settings จาก DB — เทสต์นี้แตะแค่เมธอด parse ล้วน จึงข้าม constructor
        $this->svc = (new ReflectionClass(ThaiAstrologyService::class))->newInstanceWithoutConstructor();
