 *   → `birth_time` = NULL · ผังดวงคำนวณจาก 12:00 น. ตามเดิม
 *   → แต่ AI ตอบว่า *"รับข้อมูลเวลาเกิดแล้วค่ะ ... ละเอียดขึ้นกว่าการใช้เวลาเที่ยงมาตรฐาน"*
 *     = **โกหกลูกค้าที่จ่ายเงินแล้ว**
 *   สเกลจริงตอนพบ: บิลจ่ายเงิน 1,253 ใบ มี birth_time 0 ใบ (คอลัมน์ไม่เคยถูกเขียนเลย)
 *
 * owner directive: *"บอทต้องแยกแยะเข้าใจได้เอง แม้บอกเวลาแบบไทยๆ
 *                    ก็ต้องประมาณได้ว่าเป็นเวลาสากลแบบไหน"*
 *
 * ⚠️ เทสต์นี้ใช้ PHPUnit\TestCase ตรงๆ (ไม่ใช่ Tests\TestCase) — ตรรกะล้วน ไม่แตะ DB
 *    เครื่อง dev ไม่มี MySQL ก็รันได้ (cf. rule_phpunit_needs_mysql_no_sqlite)
 */
