    /**
     * แถวที่จะ seed (ใช้ทั้ง seeder, migration และเทสต์)
     *
     * @return array<int, array{message:string, hour_from:?int, hour_to:?int}>
     */
    public static function rows(): array
    {
        $rows = [];

        foreach (self::anytime() as $text) {
            $rows[] = ['message' => $text, 'hour_from' => null, 'hour_to' => null];
        }

        foreach (self::morning() as $text) {
            $rows[] = ['message' => $text, 'hour_from' => self::MORNING[0], 'hour_to' => self::MORNING[1]];
        }

        foreach (self::evening() as $text) {
            $rows[] = ['message' => $text, 'hour_from' => self::EVENING[0], 'hour_to' => self::EVENING[1]];
        }

        return $rows;
    }

    /**
     * เพิ่มแถวที่ยังไม่มี — คืนจำนวนแถวที่สร้างใหม่
     *
     * ปลอดภัยต่อการรันซ้ำ และไม่ทับแถวที่แอดมินแก้แล้ว
     */
    public static function seed(): int
    {
        if (! Schema::hasTable('fortune_invite_messages')
            || ! Schema::hasColumn('fortune_invite_messages', 'mode')) {
            return 0;
        }

        $hasWindow = FortuneInviteMessage::supportsTimeWindow();
        $sortBase = (int) FortuneInviteMessage::withTrashed()->max('sort_order');
        $created = 0;

        foreach (self::rows() as $i => $row) {
            // ⚠️ withTrashed — แถวที่แอดมินลบไปแล้ว ห้าม seed กลับมา
            $exists = FortuneInviteMessage::withTrashed()
                ->where('mode', FortuneInviteMessage::MODE_WEB)
                ->where('message', $row['message'])
                ->exists();

            if ($exists) {
                continue;
            }

            $data = [
                'message' => $row['message'],
                'category' => FortuneInviteMessage::CATEGORY_WEB_INVITE,
                'mode' => FortuneInviteMessage::MODE_WEB,
                'is_active' => true,
                'sort_order' => $sortBase + $i + 1,
            ];

            if ($hasWindow) {
                $data['hour_from'] = $row['hour_from'];
                $data['hour_to'] = $row['hour_to'];
            }

            FortuneInviteMessage::create($data);
            $created++;
        }

        return $created;
    }

    /**
     * 🗂️ ปิดทุกหมวดยกเว้น "เชิญมาเว็บ" (ใช้ระบบเปิด/ปิดหมวดเดิม — invite_disabled_categories)
     *
     * ไม่ลบข้อความใด ๆ · เปิดกลับได้ที่หน้าแอดมิน → ข้อความชวน → ติ๊กหมวด
     * หรือ rollback migration (คืนรายการหมวดที่ปิดอยู่เดิมจากไฟล์ BACKUP_PATH)
     *
     * @param  string|null  $backupFile  path เต็มของไฟล์ backup (null = ไม่เขียน backup)
     * @return array<int, string> รายการหมวดที่ปิดหลังทำงาน
     */
    public static function focus(?string $backupFile = null): array
    {
        if (! Schema::hasTable('fortune_telling_settings')
            || ! Schema::hasColumn('fortune_telling_settings', 'invite_disabled_categories')) {
            return [];
        }

        $settings = FortuneTellingSetting::getSettings();
        $before = $settings->getDisabledInviteCategories();

        // เขียน backup ครั้งแรกครั้งเดียว — รันซ้ำห้ามทับค่าเดิมของจริง
        if ($backupFile !== null && ! is_file($backupFile)) {
            @mkdir(dirname($backupFile), 0775, true);
            file_put_contents($backupFile, json_encode([
                'disabled_before' => $before,
                'saved_at' => now()->toIso8601String(),
            ], JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT));
        }

        $others = FortuneInviteMessage::withTrashed()
            ->whereNotNull('category')
            ->where('category', '!=', FortuneInviteMessage::CATEGORY_WEB_INVITE)
            ->distinct()
            ->pluck('category')
            ->filter(fn ($c) => trim((string) $c) !== '')
            ->all();

        $disabled = array_values(array_unique(array_diff(
            array_merge($before, $others),
            [FortuneInviteMessage::CATEGORY_WEB_INVITE]
        )));

        $settings->update(['invite_disabled_categories' => $disabled]);
        FortuneTellingSetting::clearSettingsCache();

        return $disabled;
    }

    /**
     * ↩️ คืนรายการหมวดที่ปิดอยู่ก่อนเปิดแคมเปญ (ไม่มีไฟล์ backup = ไม่รู้ค่าเดิม → เปิดทุกหมวด)
     */
    public static function unfocus(?string $backupFile = null): void
    {
        if (! Schema::hasTable('fortune_telling_settings')
            || ! Schema::hasColumn('fortune_telling_settings', 'invite_disabled_categories')) {
            return;
        }

        $before = [];

        if ($backupFile !== null && is_file($backupFile)) {
            $json = json_decode((string) file_get_contents($backupFile), true);
            $before = is_array($json['disabled_before'] ?? null) ? $json['disabled_before'] : [];
            @unlink($backupFile);
        }

        FortuneTellingSetting::getSettings()->update(['invite_disabled_categories' => array_values($before)]);
        FortuneTellingSetting::clearSettingsCache();
    }

