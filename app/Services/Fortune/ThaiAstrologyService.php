    protected function formatTransitAspectLines(array $transit, int $limit = 8): string
    {
        if (empty($this->lastNatalPositions)) {
            return '';
        }

        // ดาวจรที่ "ช้าพอจะเป็นจังหวะชีวิต" — จันทร์ 2.5 วัน/ราศี, พุธ-ศุกร์ไวเกิน ⇒ ตัดออก
        $slow = self::TIMING_PLANETS;

        $natal = $this->lastNatalPositions;
        // 🌙 ไม่รู้เวลาเกิด = จันทร์กำเนิดคลาด ±6.6° ⇒ มุมที่ยิงใส่จันทร์เป็นการเดา (เหตุผลเดียวกับมุมในดวง)
        if ($this->lastLagnaBasis !== 'lagna') {
            unset($natal['Moon']);
        }

        $hits = AstroAspects::transitToNatal($transit, $natal, $slow);
        if (empty($hits)) {
            return '';
        }

        $out = "   🎯 ดาวจรกระทบดวงกำเนิด (ตัวชี้ *ช่วงเวลา* ตัวจริง — ห้ามอ้างมุมนอกรายการนี้):\n";
        foreach (array_slice($hits, 0, $limit) as $h) {
            $out .= "      {$h['transit']}(จร) {$h['name']} {$h['natal']}(กำเนิด) คลาด {$h['orb']}° — {$h['nature']}\n";
        }

        return $out;
    }

    /**
     * 📐 มุมสัมพันธ์ระหว่างดาวในดวงกำเนิด — บรรทัดพร้อมยัดเข้าพรอมต์
     *
     * เอาเฉพาะ 6 มุมที่แน่นที่สุด (orb น้อยสุด) — ใส่หมดทุกคู่ = 45 บรรทัด
     * ซึ่งเป็นสัญญาณรบกวนล้วน ๆ และโมเดลจะหยิบมั่ว
     *
     * 🌙 ไม่รู้เวลาเกิด → **ตัดจันทร์ออกจากการนับมุม** เพราะจันทร์คลาดได้ ±6.6°
     *    ซึ่งกว้างกว่า orb ของมุมส่วนใหญ่ ⇒ มุมที่มีจันทร์อยู่ด้วยคือการเดา ไม่ใช่การคำนวณ
