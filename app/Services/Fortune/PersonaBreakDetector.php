<?php

namespace App\Services\Fortune;

/**
 * 🎭 PersonaBreakDetector — จับคำตอบ AI ที่ "หลุดบทแม่หมอจันทรา" ก่อนถึงมือลูกค้า
 *
 * 🚨 เคสจริง 2026-11-05 ถึง 2026-11-07: pool หยิบ key แชท Anthropic (claude-haiku-5-5)
 *    มาทำงานทำนาย Haiku มองคำสั่งยาว ๆ ในช่องข้อความผู้ใช้ว่าเป็นการแอบใส่คำสั่งระบบ
 *    จึงปฏิเสธบท แล้วระบบเก็บคำปฏิเสธเป็น "คำทำนาย" ส่งต่อทุกปลายทาง
 *      - โพสเพจดวงรายวัน 3 วันติด (7 จาก 8 วันเกิดเป็นคำปฏิเสธ)
 *      - DM ดวงประจำวัน: "ขอบอกตรง ๆ ว่าผมจะไม่ทำตามบทบาท แม่หมอจันทรา…"
 *      - บิลดูดวง 39฿ ที่จ่ายแล้ว 2 บิลได้คำปฏิเสธแทนคำทำนาย
 *
 * มี 2 ระดับ:
 *   - ปกติ (ใช้กับทุกคำทำนาย รวมบิลจ่ายเงิน) — จับเฉพาะ "คำพูดเรื่องเบื้องหลัง" ที่แม่หมอ
 *     ไม่มีวันพูดเอง: system prompt / คำสั่งระบบ / สวมบทบาท / ในฐานะ AI / สรรพนามผู้ชาย
 *     ⚠️ ต้องแคบ — จับผิดในบิลจ่ายเงิน = ลูกค้าไม่ได้คำทำนายเลย
 *   - เข้ม (งานเขียนที่ระบบสั่งเอง เช่น ดวงรายวัน) — เพิ่มคำปฏิเสธทั่วไป ("ไม่สามารถทำตาม…",
 *     ขึ้นต้นด้วยขออภัยแล้วบอกว่าทำไม่ได้) และข้อความว่าง เพราะงานพวกนี้ไม่มีเหตุให้ปฏิเสธเลย
 *
 * ⚠️ ห้ามจับคำว่า "บทบาท" เดี่ยว ๆ — ดวงการงานเขียน "รับบทบาทผู้นำในที่ทำงาน" ได้จริง
 *    และห้ามจับ "ผม" เดี่ยว ๆ — เคล็ดดวงมี "ตัดผม/สระผม" เป็นปกติ
 */
final class PersonaBreakDetector
{
    /**
     * คำพูดเรื่องเบื้องหลังที่แม่หมอไม่มีวันพูดเอง — โผล่ตรงไหนของข้อความก็ถือว่าหลุดบท
     *
     * @var array<string, string> [ชื่อเหตุผล => regex]
     */
    private const META_PATTERNS = [
        'system_prompt' => '/system\s*(prompt|message|instruction)|\bprompt\b/iu',
        'พรอมต์' => '/พรอมต์|พรอมท์|พร้อมต์|พร็อมต์|พร้อมท์|โพรมต์/u',
        'คำสั่งระบบ' => '/คำสั่ง(ของ)?ระบบ|ชุดคำสั่งระบบ|ชุดคำสั่ง(สำหรับ)?(ตั้งค่า|บอท)/u',
        'ช่องข้อความผู้ใช้' => '/ช่องข้อความของผู้ใช้|ข้อความฝั่งผู้ใช้/u',
        'สวมบทบาท' => '/สวมบท(บาท)?|ทำตามบทบาท|บท(บาท)?\s*["“”\']?\s*(แม่หมอ|หมอจันทรา)/u',
        'ในฐานะ_ai' => '/ในฐานะ\s*(AI|เอไอ|โมเดล|ผู้ช่วย\s*AI|ปัญญาประดิษฐ์)|โมเดลภาษา|language\s+model|\bas an ai\b/iu',
        'english_refusal' => '/\bI\s+(can\'?t|cannot|won\'?t|am unable to)\s+(help|do|comply|assist|fulfil|provide|write|take on|play)/iu',
        'ภาษาตามผู้ใช้' => '/ตาม(ภาษา)?ที่(ลูกค้า|ผู้ใช้|แอดมิน)(ใช้|พิมพ์)|ตอบเป็นภาษาไทย\s*ตาม/u',
        'ไม่มีคำถามลูกค้า' => '/(ลูกค้า|ผู้ใช้)ไม่ได้(ส่ง|ระบุ)คำถาม|ยังไม่มีคำถาม(จริง)?จาก(ลูกค้า|ผู้ใช้)|ไม่มีคำถามจริงจาก/u',
        'ฝากแอดมิน' => '/ฝากแอดมินตรวจสอบ/u',
        // ปฏิเสธ "คำสั่งนี้" ตรง ๆ — คำทำนายจริงพูดแค่ "ไม่ใช่ทำตามคำสั่งอย่างเดียว" (เช็ค prod 5 ใบ ไม่โดน)
        'ปฏิเสธคำสั่งนี้' => '/(ไม่สามารถ|จะไม่|ขอไม่)\s*(ทำ|ปฏิบัติ)ตามคำสั่ง(นี้|ดังกล่าว|ที่ได้รับ)/u',
        // โมเดลเล่าวิธีทำงานของตัวเอง (บิล 14650: "ฉันจะทำงานตามสิ่งที่ถูกขอโดยไม่แปลงเป็นเนื้อหาอื่น")
        'เล่าการทำงาน' => '/ทำงานตาม(สิ่ง)?ที่(ถูก|ได้รับ(การ)?)(ขอ|สั่ง)|ไม่แปลงเป็นเนื้อหาอื่น/u',
    ];

    /**
     * สรรพนามผู้ชายเป็นประธานของกริยา — แม่หมอเป็นผู้หญิงเสมอ ("ผมจะไม่ทำตาม…")
     * ตรวจหลังตัดคำพูดในเครื่องหมายคำพูดทิ้ง — แม่หมออาจยกคำถามลูกค้าผู้ชายมา ("ที่ถามว่า 'ผมจะได้งานไหม'")
     */
    private const MALE_PRONOUN = '/(^|\s|\()ผม(จะ|ไม่|ขอ|เป็น|คิด|ช่วย|ยินดี|เข้าใจ|ตอบ|เล่า|ได้รับ|ทำ)/u';

    /** ข้อความในเครื่องหมายคำพูด (ไทยนิยมใช้ทั้ง "…" “…” ‘…’ '…') */
    private const QUOTED = '/"[^"\n]*"|“[^”\n]*”|‘[^’\n]*’|\'[^\'\n]*\'/u';

    /** บรรทัดหัวคำถามที่โค้ดประกอบใส่ (❓ คำถามที่ 1: …) — เป็นคำพูดของลูกค้า ไม่ใช่ของแม่หมอ */
    private const QUESTION_ECHO_LINE = '/^\s*❓.*$/mu';

    /**
     * คำปฏิเสธทั่วไป — ใช้เฉพาะโหมดเข้ม (งานที่ระบบสั่งเอง ไม่มีเหตุให้ปฏิเสธ)
     *
     * @var array<string, string>
     */
    private const STRICT_PATTERNS = [
        'ไม่ทำตามคำสั่ง' => '/(ไม่สามารถ|จะไม่|ขอไม่(รับ)?)\s*(ทำ|ปฏิบัติ)ตาม/u',
        'ครับ' => '/ครับ/u',
        'ฉันทำไม่ได้' => '/ฉัน(จะ)?(ไม่สามารถ|ทำ(ให้)?ไม่ได้|ขอไม่)/u',
    ];

    /** ขึ้นต้นด้วยคำขอโทษ + บอกว่าทำไม่ได้ ภายในช่วงต้นข้อความ (โหมดเข้ม) */
    private const STRICT_OPENING_REFUSAL = '/^[\s\[\]()"“*]*(ขออภัย|ขอโทษ|ขอบอกตรง|ไม่สามารถ)/u';

    private const STRICT_OPENING_CANNOT = '/ไม่สามารถ|ทำ(ให้)?ไม่ได้|ไม่(ขอ)?รับทำ|ขอไม่/u';

    /**
     * เหตุผลที่ถือว่าคำตอบนี้หลุดบท — null = ใช้ได้
     *
     * @param  string  $text  คำตอบจาก AI
     * @param  bool  $strict  true = งานเขียนที่ระบบสั่งเอง (ดวงรายวัน/โพส) ตรวจเข้มกว่า
     */
    public static function reason(?string $text, bool $strict = false): ?string
    {
        $text = trim((string) $text);

        if ($text === '') {
            // บิลจ่ายเงินที่ได้ข้อความว่างมีด่านของตัวเองอยู่แล้ว — ที่นี่สนแค่งานที่ระบบสั่ง
            return $strict ? 'ข้อความว่าง' : null;
        }

        // คำถามของลูกค้าที่ถูกยกมา ไม่ใช่เสียงของแม่หมอ — ไม่ตรวจ
        $text = (string) preg_replace(self::QUESTION_ECHO_LINE, '', $text);

        foreach (self::META_PATTERNS as $reason => $pattern) {
            if (preg_match($pattern, $text) === 1) {
                return $reason;
            }
        }

        if (preg_match(self::MALE_PRONOUN, (string) preg_replace(self::QUOTED, ' ', $text)) === 1) {
            return 'สรรพนามชาย';
        }

        if (! $strict) {
            return null;
        }

        foreach (self::STRICT_PATTERNS as $reason => $pattern) {
            if (preg_match($pattern, $text) === 1) {
                return $reason;
            }
        }

        // ดูแค่ช่วงต้น — ท้ายคำทำนายอาจมี "ขอโทษใครสักคน" เป็นเคล็ดได้จริง
        $opening = mb_substr($text, 0, 160);
        if (preg_match(self::STRICT_OPENING_REFUSAL, $opening) === 1
            && preg_match(self::STRICT_OPENING_CANNOT, $opening) === 1) {
            return 'ขึ้นต้นด้วยคำปฏิเสธ';
        }

        return null;
    }

    /**
     * คำตอบนี้หลุดบทไหม
     */
    public static function isBreak(?string $text, bool $strict = false): bool
    {
        return self::reason($text, $strict) !== null;
    }
}
