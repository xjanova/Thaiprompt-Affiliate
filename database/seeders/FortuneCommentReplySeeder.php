                    'message' => $message,
                    'category' => $category,
                    'locale' => 'th',
                    'is_active' => true,
                    'sort_order' => $sort++,
                ]);
            }
        }

        $this->command->info('✅ Seed คลังคำตอบคอมเมนต์สำเร็จ! รวม '.FortuneCommentReply::count().' ชุด');
