     *   ❌ เหตุการณ์: "เรื่องที่เกิดในกรุงเทพ"
     *   ❌ ชื่อกำกวม (เลย/ตาก/…) ต้องมีคำบอกสถานที่ในช่วงด้วย — "ไม่รู้เวลาเกิดเลย" · "ถ้าเกิดตากฝน"
