        if ($diff === 0) {
            return ['status' => 'self', 'text' => (string) ($cfg['self_text'] ?? '')];
        }
        if ($diff === 6) {
            return ['status' => 'direct', 'text' => (string) ($cfg['direct_text'] ?? '')];
        }

        return ['status' => 'none', 'text' => (string) ($cfg['none_text'] ?? '')];
    }

